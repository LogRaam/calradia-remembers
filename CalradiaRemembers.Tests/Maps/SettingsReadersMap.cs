// Code written by Gabriel Mailhot, 16/11/2026.
// docs/maps/settings.md: every MCM setting, and every place in the mod that reads it.
//
// The same bug, three times: a switch obeyed by one road and not by another that does the same thing.
// - froggyluv (22/10/2026): "Arrests and outlaws" off, "I've disabled that in options but they're still showing up":
//   the hunters' road never asked it.
// - The adult-content level (2.5.x): with adult content off, an automatic switch could still move the player onto the
//   NSFW model; the routing road never asked it.
// - Lordfadooboo (16/11/2026): "NPCs Raise World News" off, "my companions still ask to speak with me to tell me about a
//   random castle": it was read by the lords' gossip (InterceptionBehavior) and never by the companions' rumour report.
// engine-facts.md could not show the last one: it follows values into the pure rules, and this setting was read in the
// glue. Here every read is listed, rules or glue, so "who obeys this switch?" is one line, and a setting whose MCM hint
// promises something broad but which is read in ONE place asks its own question.
//
// How a read is found, from syntax: `ModSettings.X` (each ModSettings member is mapped to the CrSettings properties its
// body names), `CrSettings.Instance.X` / `CrSettings.Instance?.X`, and `s.X` where `s` is a local, field or parameter
// declared as CrSettings (or `var s = CrSettings.Instance`). Blind spots: a value read once and handed on (to the SDK as
// an option, to a helper as an argument) shows only at the read, never at the roads that use it; reflection and the MCM's
// own UI are not reads; a ModSettings member computed from other members (not from CrSettings) maps to nothing. Console
// and cr.test files (Diagnostics, ModCheats) are counted apart: they exercise a switch, they do not obey it.

#region

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class SettingsReadersMap
   {
      public const string Path = "docs/maps/settings.md";

      private const string SettingsFile = "CrSettings.cs";
      private const string FacadeFile = "ModSettings.cs";

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<SourceFile> mod = files.Where(f => f.Layer == Layer.Mod).ToList();
         SourceFile? settingsFile = mod.FirstOrDefault(f => FileName(f) == SettingsFile);
         SourceFile? facadeFile = mod.FirstOrDefault(f => FileName(f) == FacadeFile);
         if (settingsFile == null) return "";

         List<Setting> settings = SettingsOf(settingsFile);
         var names = new HashSet<string>(settings.Select(s => s.Property), StringComparer.Ordinal);
         Dictionary<string, HashSet<string>> facade = facadeFile == null ? new() : FacadeOf(facadeFile, names);

         var play = new Dictionary<string, SortedSet<string>>(StringComparer.Ordinal);
         var exercise = new Dictionary<string, SortedSet<string>>(StringComparer.Ordinal);
         foreach (Setting s in settings)
         {
            play[s.Property] = new SortedSet<string>(StringComparer.Ordinal);
            exercise[s.Property] = new SortedSet<string>(StringComparer.Ordinal);
         }

         foreach (SourceFile file in mod.Where(f => FileName(f) != SettingsFile && FileName(f) != FacadeFile))
         {
            Dictionary<string, SortedSet<string>> into = IsDiagnostics(file) ? exercise : play;
            foreach ((string property, string reader) in ReadsIn(file, names, facade))
               into[property].Add(reader);
         }

         var sb = new StringBuilder();
         sb.AppendLine("# Settings: who obeys each MCM switch");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("A switch obeyed by one road and not by another that does the same thing has shipped three times (\"Arrests and");
         sb.AppendLine("outlaws\" off and the hunters still rode; adult content off and the NSFW model still took over; \"NPCs Raise World");
         sb.AppendLine("News\" off and companions still brought news). **Before adding a road that does what a setting governs (a new way to");
         sb.AppendLine("approach, to write, to pick a model), find the setting here and make the new road one of its readers.** When a");
         sb.AppendLine("player says \"I turned it off and it still happens\", the readers listed here are the roads that obey it: the one doing");
         sb.AppendLine("it is missing from the list. Read from syntax; blind spots in the header of `SettingsReadersMap.cs` (a value handed");
         sb.AppendLine("on to the SDK or a helper shows only where it is read).");
         sb.AppendLine();
         sb.AppendLine($"{settings.Count} settings; a reader is `Type.Member`. Console and cr.test reads are counted apart (they exercise a switch, they do not obey it).");
         sb.AppendLine();

         List<Setting> single = settings.Where(s => play[s.Property].Count == 1).ToList();
         sb.AppendLine("## Read by one member only");
         sb.AppendLine();
         sb.AppendLine("Fine when the setting governs one thing. Worth a look when its hint promises more (\"an NPC\", \"characters\",");
         sb.AppendLine("\"any letter\"): every other road doing that thing ignores it.");
         sb.AppendLine();
         sb.AppendLine("| Setting | Read by |");
         sb.AppendLine("|---|---|");
         foreach (Setting s in single.OrderBy(s => s.Label, StringComparer.Ordinal))
            sb.AppendLine($"| {DocText.Cell(s.Label)} (`{s.Property}`) | `{play[s.Property].First()}` |");
         sb.AppendLine();

         List<Setting> unread = settings.Where(s => play[s.Property].Count == 0).ToList();
         sb.AppendLine("## Read by no road of play");
         sb.AppendLine();
         sb.AppendLine("A switch the player can move that changes nothing in play, unless it is read where this map is blind (handed");
         sb.AppendLine("on at load, read by reflection). Each one is either a dead switch or a blind spot to name.");
         sb.AppendLine();
         if (unread.Count == 0) sb.AppendLine("(none)");
         foreach (Setting s in unread.OrderBy(s => s.Label, StringComparer.Ordinal))
            sb.AppendLine($"- {DocText.Cell(s.Label)} (`{s.Property}`){(exercise[s.Property].Count > 0 ? ", exercised by cr.test or the console only" : "")}");
         sb.AppendLine();

         sb.AppendLine("## Every setting, by MCM group");
         foreach (IGrouping<string, Setting> group in settings.GroupBy(s => s.Group).OrderBy(g => g.Key, StringComparer.Ordinal))
         {
            sb.AppendLine();
            sb.AppendLine($"### {group.Key}");
            sb.AppendLine();
            sb.AppendLine("| Setting | Readers in play | cr.test / console |");
            sb.AppendLine("|---|---|---|");
            foreach (Setting s in group.OrderBy(s => s.Label, StringComparer.Ordinal))
            {
               string readers = play[s.Property].Count == 0 ? "(none)" : string.Join(", ", play[s.Property].Select(r => $"`{r}`"));
               sb.AppendLine($"| {DocText.Cell(s.Label)} (`{s.Property}`) | {readers} | {exercise[s.Property].Count} |");
            }
         }
         sb.AppendLine();

         return sb.ToString();
      }

      #region private

      private sealed record Setting(string Property, string Label, string Group);

      private static string FileName(SourceFile f) => System.IO.Path.GetFileName(f.RelativePath);

      private static bool IsDiagnostics(SourceFile f)
         => ("/" + f.RelativePath).Contains("/Diagnostics/") || FileName(f).StartsWith("ModCheats", StringComparison.Ordinal);

      /// <summary>Every property carrying an MCM SettingProperty attribute (buttons excluded: they act, nothing reads them).</summary>
      private static List<Setting> SettingsOf(SourceFile file)
      {
         var found = new List<Setting>();
         foreach (PropertyDeclarationSyntax p in file.Root.DescendantNodes().OfType<PropertyDeclarationSyntax>())
         {
            List<AttributeSyntax> attrs = p.AttributeLists.SelectMany(l => l.Attributes).ToList();
            AttributeSyntax? setting = attrs.FirstOrDefault(a => {
               string n = a.Name.ToString();
               return n.StartsWith("SettingProperty", StringComparison.Ordinal) && n != "SettingPropertyGroup" && n != "SettingPropertyButton";
            });
            if (setting == null) continue;

            AttributeSyntax? group = attrs.FirstOrDefault(a => a.Name.ToString() == "SettingPropertyGroup");
            found.Add(new Setting(p.Identifier.Text, Label(setting) ?? p.Identifier.Text, Label(group) ?? "(no group)"));
         }

         return found;
      }

      /// <summary>The first string argument without its translation id: "{=CR_MCM_X}NPCs Raise World News" gives "NPCs Raise World News".</summary>
      private static string? Label(AttributeSyntax? attr)
      {
         if (attr?.ArgumentList == null || attr.ArgumentList.Arguments.Count == 0) return null;
         if (attr.ArgumentList.Arguments[0].Expression is not LiteralExpressionSyntax lit || !lit.Token.IsKind(SyntaxKind.StringLiteralToken)) return null;

         string text = lit.Token.ValueText;
         int close = text.StartsWith("{=", StringComparison.Ordinal) ? text.IndexOf('}') : -1;

         return close >= 0 ? text.Substring(close + 1) : text;
      }

      /// <summary>
      ///   Each ModSettings member and the CrSettings properties it reads, directly or through other ModSettings members
      ///   (WorldInitiative reads thirteen settings through InitiativeAtOnce and its siblings: without following those,
      ///   the first run of this map listed all thirteen as read by no road of play).
      /// </summary>
      private static Dictionary<string, HashSet<string>> FacadeOf(SourceFile file, HashSet<string> names)
      {
         var direct = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
         var calls = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
         List<MemberDeclarationSyntax> members = file.Root.DescendantNodes().OfType<MemberDeclarationSyntax>()
                                                     .Where(m => m is PropertyDeclarationSyntax or MethodDeclarationSyntax).ToList();
         string IdOf(MemberDeclarationSyntax m) => m is PropertyDeclarationSyntax prop ? prop.Identifier.Text : ((MethodDeclarationSyntax) m).Identifier.Text;
         var facadeIds = new HashSet<string>(members.Select(IdOf), StringComparer.Ordinal);

         foreach (MemberDeclarationSyntax m in members)
         {
            string id = IdOf(m);
            if (!direct.ContainsKey(id)) { direct[id] = new HashSet<string>(StringComparer.Ordinal); calls[id] = new HashSet<string>(StringComparer.Ordinal); }
            foreach (SimpleNameSyntax n in m.DescendantNodes().OfType<SimpleNameSyntax>())
            {
               string text = n.Identifier.Text;
               bool accessed = n.Parent is MemberAccessExpressionSyntax ma && ma.Name == n || n.Parent is MemberBindingExpressionSyntax;
               if (accessed && names.Contains(text)) direct[id].Add(text);
               else if (!accessed && text != id && facadeIds.Contains(text)) calls[id].Add(text);
            }
         }

         var map = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
         foreach (string id in direct.Keys)
         {
            var all = new HashSet<string>(StringComparer.Ordinal);
            var seen = new HashSet<string>(StringComparer.Ordinal) {id};
            var todo = new Stack<string>(new[] {id});
            while (todo.Count > 0)
            {
               string next = todo.Pop();
               all.UnionWith(direct[next]);
               foreach (string c in calls[next])
                  if (seen.Add(c)) todo.Push(c);
            }

            if (all.Count > 0) map[id] = all;
         }

         return map;
      }

      private static IEnumerable<(string Property, string Reader)> ReadsIn(SourceFile file, HashSet<string> names, Dictionary<string, HashSet<string>> facade)
      {
         HashSet<string> settingsVars = SettingsVariables(file);

         foreach (SimpleNameSyntax name in file.Root.DescendantNodes().OfType<SimpleNameSyntax>())
         {
            string member = name.Identifier.Text;
            string? target = name.Parent switch {
               MemberAccessExpressionSyntax ma when ma.Name == name => ma.Expression.ToString(),
               MemberBindingExpressionSyntax mb => (mb.Parent?.Parent as ConditionalAccessExpressionSyntax)?.Expression.ToString()
                                                   ?? mb.Ancestors().OfType<ConditionalAccessExpressionSyntax>().FirstOrDefault()?.Expression.ToString(),
               _ => null
            };
            if (target == null) continue;

            string last = target.Split('.').Last().Trim();
            IEnumerable<string> properties;
            if (last == "ModSettings" && facade.TryGetValue(member, out HashSet<string>? mapped)) properties = mapped;
            else if (names.Contains(member) && (target.Contains("CrSettings") || settingsVars.Contains(last))) properties = new[] {member};
            else continue;

            string reader = ReaderOf(name);
            foreach (string p in properties) yield return (p, reader);
         }
      }

      /// <summary>Locals, fields and parameters declared as CrSettings, or assigned from CrSettings.Instance with var.</summary>
      private static HashSet<string> SettingsVariables(SourceFile file)
      {
         var vars = new HashSet<string>(StringComparer.Ordinal);
         foreach (VariableDeclarationSyntax d in file.Root.DescendantNodes().OfType<VariableDeclarationSyntax>())
         {
            bool typed = d.Type.ToString().Split('.').Last() == "CrSettings";
            foreach (VariableDeclaratorSyntax v in d.Variables)
               if (typed || d.Type.IsVar && v.Initializer?.Value.ToString().Contains("CrSettings.Instance") == true)
                  vars.Add(v.Identifier.Text);
         }

         foreach (ParameterSyntax p in file.Root.DescendantNodes().OfType<ParameterSyntax>())
            if (p.Type?.ToString().Split('.').Last() == "CrSettings")
               vars.Add(p.Identifier.Text);

         foreach (DeclarationPatternSyntax dp in file.Root.DescendantNodes().OfType<DeclarationPatternSyntax>())
            if (dp.Type.ToString().Split('.').Last() == "CrSettings" && dp.Designation is SingleVariableDesignationSyntax sv)
               vars.Add(sv.Identifier.Text);

         return vars;
      }

      /// <summary>"Type.Member" of the innermost type and member around the read; "Type.(field)" for an initializer.</summary>
      private static string ReaderOf(SimpleNameSyntax name)
      {
         string type = name.Ancestors().OfType<BaseTypeDeclarationSyntax>().FirstOrDefault()?.Identifier.Text ?? "(none)";
         string member = name.Ancestors().Select(a => a switch {
            MethodDeclarationSyntax m => m.Identifier.Text,
            PropertyDeclarationSyntax p => p.Identifier.Text,
            ConstructorDeclarationSyntax => ".ctor",
            LocalFunctionStatementSyntax => null,
            AccessorDeclarationSyntax => null,
            FieldDeclarationSyntax f => f.Declaration.Variables.FirstOrDefault()?.Identifier.Text,
            EventDeclarationSyntax e => e.Identifier.Text,
            OperatorDeclarationSyntax => "operator",
            _ => null
         }).FirstOrDefault(n => n != null) ?? "(member)";

         return $"{type}.{member}";
      }

      #endregion
   }
}

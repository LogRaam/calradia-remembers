   internal static class DependencyMap
   {
      public const string Path = "docs/maps/dependencies.md";

      private static readonly string[] OurRoots = {"CalradiaRemembers", "NpcMemoryService"};

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         Dictionary<string, SortedSet<string>> uses = EdgesOf(files, out Dictionary<(string, string), SortedSet<string>> origins);
         Dictionary<string, SortedSet<string>> usedBy = Invert(uses);
         List<string> nodes = uses.Keys.Union(usedBy.Keys).OrderBy(n => n, StringComparer.Ordinal).ToList();

         var sb = new StringBuilder();
         sb.AppendLine("# Dependencies: which namespace uses which");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("Read from `using` directives and from qualified names (`Standing.X`, `Logic.Y`), resolved against the");
         sb.AppendLine("enclosing namespaces as the compiler does. No compilation is needed; an unused import still counts. A NEW");
         sb.AppendLine("LINE in this file means a namespace has started to know about another one, which is worth a second look.");
         sb.AppendLine();

         AppendCycles(sb, nodes, uses);
         AppendFanTable(sb, nodes, uses, usedBy);
         AppendMutualPairs(sb, MutualPairs(uses, origins));
         AppendAdjacency(sb, nodes, uses, usedBy);

         return sb.ToString();
      }

      /// <summary>
      ///   One pair of namespaces that use each other directly, with the files that create each direction. The two
      ///   names are in ordinal order, so a pair is listed once.
      /// </summary>
      internal sealed class MutualPair
      {
         public string First { get; init; } = "";
         public string Second { get; init; } = "";

         /// <summary>The files in <see cref="First" /> that name <see cref="Second" />.</summary>
         public IReadOnlyList<string> FirstUsesSecondIn { get; init; } = Array.Empty<string>();

         /// <summary>The files in <see cref="Second" /> that name <see cref="First" />.</summary>
         public IReadOnlyList<string> SecondUsesFirstIn { get; init; } = Array.Empty<string>();

         /// <summary>How many files hold up the weaker direction: 1 means one file away from no longer being a pair.</summary>
         public int WeakerSide => Math.Min(FirstUsesSecondIn.Count, SecondUsesFirstIn.Count);
      }

      /// <summary>Every pair of our namespaces that use each other directly, the pairs held up by the fewest files first.</summary>
      public static IReadOnlyList<MutualPair> MutualPairs(IReadOnlyList<SourceFile> files)
      {
         Dictionary<string, SortedSet<string>> uses = EdgesOf(files, out Dictionary<(string, string), SortedSet<string>> origins);

         return MutualPairs(uses, origins);
      }

      /// <summary>
      ///   The shortest cycle through <paramref name="ns" />, as hops "A -> B (a file of A that names B)", or empty when it
      ///   is in none. A blocking failure names what to change (14/11/2026: "a namespace joined a cycle" twice in one day,
      ///   and both times the closing edge had to be guessed); cutting any one hop breaks this cycle.
      /// </summary>
      public static IReadOnlyList<string> ShortestCycleThrough(IReadOnlyList<SourceFile> files, string ns)
      {
         Dictionary<string, SortedSet<string>> uses = EdgesOf(files, out Dictionary<(string, string), SortedSet<string>> origins);
         if (!uses.ContainsKey(ns)) return Array.Empty<string>();

         var cameFrom = new Dictionary<string, string>(StringComparer.Ordinal);
         var queue = new Queue<string>();
         foreach (string next in uses[ns])
            if (!cameFrom.ContainsKey(next))
            {
               cameFrom[next] = ns;
               queue.Enqueue(next);
            }

         while (queue.Count > 0)
         {
            string at = queue.Dequeue();
            if (at == ns) break;
            if (!uses.TryGetValue(at, out SortedSet<string>? targets)) continue;

            foreach (string next in targets)
               if (!cameFrom.ContainsKey(next))
               {
                  cameFrom[next] = at;
                  queue.Enqueue(next);
               }
         }

         if (!cameFrom.ContainsKey(ns)) return Array.Empty<string>();

         var path = new List<string> {ns};
         for (string at = cameFrom[ns]; at != ns; at = cameFrom[at]) path.Add(at);
         path.Add(ns);
         path.Reverse();

         return path.Zip(path.Skip(1), (a, b) => $"{a} -> {b} ({origins[(a, b)].First()})").ToList();
      }

      #region private

      private static bool IsOurs(string ns) => OurRoots.Any(r => ns == r || ns.StartsWith(r + ".", StringComparison.Ordinal));

      private static Dictionary<string, SortedSet<string>> EdgesOf(
         IReadOnlyList<SourceFile> files, out Dictionary<(string, string), SortedSet<string>> origins)
      {
         var uses = new Dictionary<string, SortedSet<string>>();
         var found = new Dictionary<(string, string), SortedSet<string>>();

         void Add(string from, string to, SourceFile file)
         {
            uses[from].Add(to);
            if (!found.TryGetValue((from, to), out SortedSet<string>? where)) found[(from, to)] = where = new SortedSet<string>(StringComparer.Ordinal);
            where.Add(file.RelativePath.Replace('\\', '/'));
         }

         Dictionary<string, HashSet<string>> typesIn = TypesByNamespace(files);

         foreach (SourceFile file in files)
         {
            string from = file.Namespace;
            if (!IsOurs(from)) continue;

            if (!uses.ContainsKey(from)) uses[from] = new SortedSet<string>(StringComparer.Ordinal);

            foreach (UsingDirectiveSyntax directive in file.Root.DescendantNodes().OfType<UsingDirectiveSyntax>())
            {
               string? to = directive.Name?.ToString();
               if (to == null || !IsOurs(to) || to == from) continue;

               Add(from, to, file);
            }

            foreach (string to in QualifiedTargets(file, from, typesIn))
               if (to != from) Add(from, to, file);

            foreach (string to in EnclosingTargets(file, from, typesIn))
               Add(from, to, file);
         }

         origins = found;

         return uses;
      }

      /// <summary>
      ///   The namespaces a file names through qualified references. Each dotted name is tried prefix by prefix, longest
      ///   first, against the enclosing namespaces innermost first, the way the compiler resolves `Standing.X` written
      ///   inside CalradiaRemembers.Chat to CalradiaRemembers.Standing.
      /// </summary>
      private static IEnumerable<string> QualifiedTargets(SourceFile file, string from, Dictionary<string, HashSet<string>> typesIn)
      {
         var found = new HashSet<string>(StringComparer.Ordinal);
         var scopes = new List<string>();
         for (string scope = from; !string.IsNullOrEmpty(scope); scope = scope.Contains('.') ? scope.Substring(0, scope.LastIndexOf('.')) : "")
            scopes.Add(scope);
         scopes.Add("");

         foreach (ExpressionSyntax node in file.Root.DescendantNodes().OfType<ExpressionSyntax>()
                                             .Where(n => n is QualifiedNameSyntax || n is MemberAccessExpressionSyntax))
         {
            string text = node.ToString();
            if (!IsDottedName(text)) continue;

            // A prefix counts only when the NEXT segment is a type declared in that namespace: "Settings.Current" where
            // Settings is a property, or "Map.X" on a local, must not read as the namespace of the same name.
            string[] parts = text.Split('.');
            for (int take = parts.Length - 1; take >= 1; take--)
            {
               string prefix = string.Join(".", parts.Take(take));
               string next = parts[take];
               string? hit = scopes.Select(sc => sc.Length == 0 ? prefix : sc + "." + prefix)
                                   .FirstOrDefault(ns => typesIn.TryGetValue(ns, out HashSet<string>? types) && types.Contains(next));
               if (hit == null) continue;

               found.Add(hit);
               break;
            }
         }

         return found;
      }

      /// <summary>
      ///   The enclosing namespaces a file reaches by a BARE type name, with no using and no qualifier: inside
      ///   CalradiaRemembers.Logic.Nemesis, `IRandomSource` is CalradiaRemembers.Logic's, because the compiler looks in
      ///   each enclosing namespace, innermost first, before the file's usings. A name the file's own namespace declares
      ///   stays there; the member side of `x.Name` is a member, not a type.
      /// </summary>
      private static IEnumerable<string> EnclosingTargets(SourceFile file, string from, Dictionary<string, HashSet<string>> typesIn)
      {
         var enclosing = new List<string>();
         for (string scope = from; scope.Contains('.');)
         {
            scope = scope.Substring(0, scope.LastIndexOf('.'));
            if (IsOurs(scope)) enclosing.Add(scope);
         }

         if (enclosing.Count == 0) return Array.Empty<string>();

         typesIn.TryGetValue(from, out HashSet<string>? own);
         var found = new HashSet<string>(StringComparer.Ordinal);

         foreach (IdentifierNameSyntax id in file.Root.DescendantNodes().OfType<IdentifierNameSyntax>())
         {
            if (id.Parent is MemberAccessExpressionSyntax access && access.Name == id) continue;
            if (id.Parent is QualifiedNameSyntax qualified && qualified.Right == id) continue;
            // A name being CALLED is a method, never a type: `Same(a, b)` in Logic.War read as the type `Same` of
            // Logic and drew a false edge (15/11/2026).
            if (id.Parent is InvocationExpressionSyntax call && call.Expression == id) continue;

            string name = id.Identifier.Text;
            if (own != null && own.Contains(name)) continue;

            string? hit = enclosing.FirstOrDefault(ns => typesIn.TryGetValue(ns, out HashSet<string>? types) && types.Contains(name));
            if (hit != null) found.Add(hit);
         }

         return found;
      }

      /// <summary>
      ///   Every type our code declares at the top of a namespace (classes, structs, records, interfaces, enums,
      ///   delegates). A type nested in another is left out: outside its file it is only ever named through its outer
      ///   type, and a private nested `Same` otherwise answers for any bare `Same` in the namespaces below (15/11/2026).
      /// </summary>
      private static Dictionary<string, HashSet<string>> TypesByNamespace(IReadOnlyList<SourceFile> files)
      {
         var map = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
         foreach (SourceFile f in files)
         {
            if (f.Namespace == null || !IsOurs(f.Namespace)) continue;
            if (!map.TryGetValue(f.Namespace, out HashSet<string>? set)) map[f.Namespace] = set = new HashSet<string>(StringComparer.Ordinal);

            foreach (BaseTypeDeclarationSyntax t in f.Root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>().Where(t => t.Parent is not TypeDeclarationSyntax)) set.Add(t.Identifier.Text);
            foreach (DelegateDeclarationSyntax d in f.Root.DescendantNodes().OfType<DelegateDeclarationSyntax>().Where(d => d.Parent is not TypeDeclarationSyntax)) set.Add(d.Identifier.Text);
         }

         return map;
      }

      private static bool IsDottedName(string text)
      {
         if (string.IsNullOrEmpty(text) || !text.Contains('.')) return false;

         foreach (char c in text)
            if (!(char.IsLetterOrDigit(c) || c == '_' || c == '.')) return false;

         return char.IsLetter(text[0]) || text[0] == '_';
      }

      private static Dictionary<string, SortedSet<string>> Invert(Dictionary<string, SortedSet<string>> uses)
      {
         var usedBy = new Dictionary<string, SortedSet<string>>();

         foreach ((string from, SortedSet<string> targets) in uses)
            foreach (string to in targets)
            {
               if (!usedBy.ContainsKey(to)) usedBy[to] = new SortedSet<string>(StringComparer.Ordinal);
               usedBy[to].Add(from);
            }

         return usedBy;
      }

      private static void AppendCycles(StringBuilder sb, List<string> nodes, Dictionary<string, SortedSet<string>> uses)
      {
         List<List<string>> groups = StronglyConnected(nodes, uses).Where(g => g.Count > 1)
                                                                    .Select(g => g.OrderBy(n => n, StringComparer.Ordinal).ToList())
                                                                    .OrderByDescending(g => g.Count)
                                                                    .ThenBy(g => g[0], StringComparer.Ordinal)
                                                                    .ToList();

         sb.AppendLine("## Cycles");
         sb.AppendLine();
         sb.AppendLine("Namespaces that reach each other, directly or through others. Inside a group nothing can be understood, tested");
         sb.AppendLine("or moved alone. A group that GROWS is the signal; one that shrinks is the work paying off.");
         sb.AppendLine();

         if (groups.Count == 0)
         {
            sb.AppendLine("None.");
            sb.AppendLine();

            return;
         }

         foreach (List<string> group in groups)
         {
            sb.AppendLine($"### A group of {group.Count}");
            sb.AppendLine();
            foreach (string ns in group) sb.AppendLine($"- `{ns}`");
            sb.AppendLine();
         }
      }

      private static void AppendFanTable(
         StringBuilder sb, List<string> nodes, Dictionary<string, SortedSet<string>> uses, Dictionary<string, SortedSet<string>> usedBy)
      {
         sb.AppendLine("## Who knows the most, and who is known the most");
         sb.AppendLine();
         sb.AppendLine("`Uses` high: a namespace that knows too many others, and breaks when any of them moves. `Used by` high: a");
         sb.AppendLine("foundation, which is fine as long as it is stable and uses little itself.");
         sb.AppendLine();
         // The table is in NAME order, so a count that moves changes its own row in place. It was ranked by count until
         // 15/11/2026: a namespace gaining one edge was shown as a row removed here and a row added there, which read
         // as two changes and hid which one it was. The ranking is the two short lines above the table.
         sb.AppendLine("Uses the most: " + string.Join(", ", nodes.OrderByDescending(n => Count(uses, n)).ThenBy(n => n, StringComparer.Ordinal).Take(5).Select(n => $"`{n}` ({Count(uses, n)})")) + ".");
         sb.AppendLine("Used by the most: " + string.Join(", ", nodes.OrderByDescending(n => Count(usedBy, n)).ThenBy(n => n, StringComparer.Ordinal).Take(5).Select(n => $"`{n}` ({Count(usedBy, n)})")) + ".");
         sb.AppendLine();
         sb.AppendLine("| Namespace | Uses | Used by |");
         sb.AppendLine("|---|---|---|");

         foreach (string ns in nodes)
            sb.AppendLine($"| `{ns}` | {Count(uses, ns)} | {Count(usedBy, ns)} |");

         sb.AppendLine();
      }

      private static void AppendAdjacency(
         StringBuilder sb, List<string> nodes, Dictionary<string, SortedSet<string>> uses, Dictionary<string, SortedSet<string>> usedBy)
      {
         sb.AppendLine("## Every namespace, and its edges");
         sb.AppendLine();

         foreach (string ns in nodes)
         {
            sb.AppendLine($"### {ns}");
            sb.AppendLine();
            sb.AppendLine("- uses: " + Listed(uses, ns));
            sb.AppendLine("- used by: " + Listed(usedBy, ns));
            sb.AppendLine();
         }
      }

      private static List<MutualPair> MutualPairs(
         Dictionary<string, SortedSet<string>> uses, Dictionary<(string, string), SortedSet<string>> origins)
      {
         var pairs = new List<MutualPair>();

         foreach ((string from, SortedSet<string> targets) in uses)
            foreach (string to in targets)
            {
               if (string.CompareOrdinal(from, to) >= 0) continue;
               if (!uses.TryGetValue(to, out SortedSet<string>? back) || !back.Contains(from)) continue;

               pairs.Add(new MutualPair {
                  First = from, Second = to,
                  FirstUsesSecondIn = origins[(from, to)].ToList(),
                  SecondUsesFirstIn = origins[(to, from)].ToList()
               });
            }

         return pairs.OrderBy(p => p.WeakerSide)
                     .ThenBy(p => p.First, StringComparer.Ordinal)
                     .ThenBy(p => p.Second, StringComparer.Ordinal)
                     .ToList();
      }

      private static void AppendMutualPairs(StringBuilder sb, IReadOnlyList<MutualPair> pairs)
      {
         sb.AppendLine("## Pairs that use each other directly");
         sb.AppendLine();
         sb.AppendLine("Where to cut a cycle. Each pair lists the files that create each direction, the pairs held up by the fewest");
         sb.AppendLine("files first: a side resting on ONE file is one file away from untangling the pair. `RatchetTests` pins the count.");
         sb.AppendLine();
         sb.AppendLine($"{pairs.Count} pair(s); {pairs.Count(p => p.WeakerSide == 1)} with a side resting on one file.");
         sb.AppendLine();

         foreach (MutualPair pair in pairs)
         {
            sb.AppendLine($"#### `{pair.First}` and `{pair.Second}`");
            sb.AppendLine();
            sb.AppendLine($"- `{pair.First}` uses `{pair.Second}` in {Files(pair.FirstUsesSecondIn)}");
            sb.AppendLine($"- `{pair.Second}` uses `{pair.First}` in {Files(pair.SecondUsesFirstIn)}");
            sb.AppendLine();
         }
      }

      /// <summary>The first three files by name, then a count: enough to point at the cut without a wall of paths.</summary>
      private static string Files(IReadOnlyList<string> files)
      {
         string shown = string.Join(", ", files.Take(3).Select(f => $"`{f}`"));

         return files.Count <= 3 ? $"{files.Count} file(s): {shown}" : $"{files.Count} files: {shown}, and {files.Count - 3} more";
      }

      private static int Count(Dictionary<string, SortedSet<string>> edges, string ns) => edges.TryGetValue(ns, out SortedSet<string>? set) ? set.Count : 0;

      private static string Listed(Dictionary<string, SortedSet<string>> edges, string ns)
         => edges.TryGetValue(ns, out SortedSet<string>? set) && set.Count > 0 ? string.Join(", ", set.Select(n => $"`{n}`")) : "nothing";

      /// <summary>Tarjan's strongly connected components, iterating nodes in a fixed order so the output is deterministic.</summary>
      private static List<List<string>> StronglyConnected(List<string> nodes, Dictionary<string, SortedSet<string>> uses)
      {
         var index = new Dictionary<string, int>();
         var low = new Dictionary<string, int>();
         var onStack = new HashSet<string>();
         var stack = new Stack<string>();
         var result = new List<List<string>>();
         var next = 0;

         void Visit(string v)
         {
            index[v] = low[v] = next++;
            stack.Push(v);
            onStack.Add(v);

            if (uses.TryGetValue(v, out SortedSet<string>? targets))
               foreach (string w in targets)
                  if (!index.ContainsKey(w))
                  {
                     Visit(w);
                     low[v] = Math.Min(low[v], low[w]);
                  }
                  else if (onStack.Contains(w))
                     low[v] = Math.Min(low[v], index[w]);

            if (low[v] != index[v]) return;

            var group = new List<string>();
            string member;
            do
            {
               member = stack.Pop();
               onStack.Remove(member);
               group.Add(member);
            } while (member != v);

            result.Add(group);
         }

         foreach (string node in nodes)
            if (!index.ContainsKey(node))
               Visit(node);

         return result;
      }

      #endregion
   }

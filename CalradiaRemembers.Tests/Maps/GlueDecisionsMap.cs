// Code written by Gabriel Mailhot, 14/11/2026.
// docs/maps/glue-decisions.md: decisions made in the engine glue instead of in a pure rule. Gabriel, 14/11/2026: "est-ce que
// nous pourrions ajouter des MAPS qui aideraient a mettre en pratique le SOLID, Tell Don't Ask et autres bonnes pratiques".
// A principle cannot be measured; its breaches that this project has paid for can. The house rule is Tell Don't Ask in its
// own terms: the decision lives in a pure policy of CalradiaRemembers.Logic, and the glue reads the game, hands the facts
// over and applies the answer. When the glue compares a fact of the game with a number written in place, it decides for
// itself, out of reach of the tests, free to drift from the copy next door. Paid for twice: the affection bar lived as a
// literal 50 in three places that agreed until one moved; and rank, read as Clan.Tier, was decided four ways under four
// names (engine-facts.md). The regard family was walled off on 26/09/2026 (RatchetTests, inline regard at 0); this is
// the same measure for every fact.
//
// What counts: a comparison (<, <=, >, >=, or a relational pattern `{Loyalty: >= 50}`) in the mod's own code, outside
// Diagnostics and the console (ModCheats), between a bare number and a FACT READ OFF AN OBJECT (a member access, or a
// method named Get...). Left out as noise, measured on the first run (330 bare comparisons, mostly not decisions): 0, 1
// and -1 (emptiness and sign tests), numbers under 0.01 (float epsilons), Count and Length (list caps, text truncation),
// and loop conditions.
//
// Blind spots: a fact read into a local first (`int rel = ...; if (rel >= 30)`) is missed; a named constant in the glue is
// not counted (constants.md lists those); equality tests are not counted (`tier == 6` is rarer and often an id).

#region

using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class GlueDecisionsMap
   {
      public const string Path = "docs/maps/glue-decisions.md";

      private static readonly string[] NotAFact = {"Count", "Length", "Capacity"};

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<Entry> entries = Entries(files);
         var sb = new StringBuilder();

         sb.AppendLine("# Decisions made in the glue: facts of the game compared with a bare number");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("Tell Don't Ask, in this project's terms: a decision lives in a pure policy of `CalradiaRemembers.Logic`, where a");
         sb.AppendLine("test can hold it and a second copy can be seen; the glue reads the game, hands over the facts and applies the");
         sb.AppendLine("answer. Each line below is the glue deciding for itself: a fact read off an object, compared with a number");
         sb.AppendLine("written in place. Moving one into a policy (or pointing it at a named rung) lowers the count;");
         sb.AppendLine("`RatchetTests` refuses a new one.");
         sb.AppendLine();
         sb.AppendLine("**Blind spots.** A fact read into a local first is missed; a named constant in the glue is not counted");
         sb.AppendLine("(`constants.md` lists those); equality tests are not counted. Diagnostics and the console are left out. Not");
         sb.AppendLine("counted as decisions: 0, 1 and -1, numbers under 0.01, `Count` and `Length`, loop conditions.");
         sb.AppendLine();
         sb.AppendLine($"**{entries.Count} decisions** in {entries.Select(e => e.Namespace).Distinct().Count()} namespaces.");
         sb.AppendLine();

         foreach (IGrouping<string, Entry> ns in entries.GroupBy(e => e.Namespace).OrderBy(g => g.Key, StringComparer.Ordinal))
         {
            sb.AppendLine($"## {ns.Key} ({ns.Count()})");
            sb.AppendLine();
            foreach (Entry e in ns.OrderBy(e => e.Where, StringComparer.Ordinal).ThenBy(e => e.Expression, StringComparer.Ordinal))
               sb.AppendLine($"- `{e.Where}`: `{DocText.Cell(e.Expression)}`");
            sb.AppendLine();
         }

         return sb.ToString();
      }

      /// <summary>How many decisions the glue makes against a bare number (the ratchet's measure).</summary>
      public static int Count(IReadOnlyList<SourceFile> files) => Entries(files).Count;

      #region private

      private sealed record Entry(string Namespace, string Where, string Expression);

      private static List<Entry> Entries(IReadOnlyList<SourceFile> files)
      {
         var seen = new HashSet<(string, string, string)>();
         var entries = new List<Entry>();

         foreach (SourceFile file in files.Where(InScope))
         {
            foreach (BinaryExpressionSyntax binary in file.Root.DescendantNodes().OfType<BinaryExpressionSyntax>())
            {
               if (!IsRelational(binary.Kind()) || InLoopCondition(binary)) continue;

               bool leftNumber = IsDecisionNumber(binary.Left), rightNumber = IsDecisionNumber(binary.Right);
               if (leftNumber == rightNumber) continue;
               if (!ReadsAFact(leftNumber ? binary.Right : binary.Left)) continue;

               Add(file, binary, binary.ToString());
            }

            foreach (RelationalPatternSyntax pattern in file.Root.DescendantNodes().OfType<RelationalPatternSyntax>())
            {
               if (!IsDecisionNumber(pattern.Expression)) continue;
               string member = (pattern.Parent as SubpatternSyntax)?.ExpressionColon?.Expression.ToString()
                               ?? (pattern.Parent as SubpatternSyntax)?.NameColon?.Name.Identifier.Text;
               if (member == null || NotAFact.Contains(member.Split('.').Last(), StringComparer.Ordinal)) continue;

               Add(file, pattern, $"{member}: {pattern}");
            }
         }

         return entries;

         void Add(SourceFile file, SyntaxNode node, string expression)
         {
            string owner = node.Ancestors().OfType<BaseTypeDeclarationSyntax>().FirstOrDefault()?.Identifier.Text ?? "?";
            string member = node.Ancestors().OfType<MemberDeclarationSyntax>().Select(MemberName).FirstOrDefault(n => n != null) ?? "?";
            string text = Regex.Replace(expression, @"\s+", " ");
            if (seen.Add((file.Namespace, owner + "." + member, text))) entries.Add(new Entry(file.Namespace, owner + "." + member, text));
         }
      }

      private static bool InScope(SourceFile file)
         => file.Layer == Layer.Mod
            && !file.RelativePath.StartsWith("Diagnostics/", StringComparison.Ordinal)
            && !System.IO.Path.GetFileName(file.RelativePath).StartsWith("ModCheats", StringComparison.Ordinal);

      private static bool IsRelational(SyntaxKind kind)
         => kind is SyntaxKind.LessThanExpression or SyntaxKind.LessThanOrEqualExpression
                 or SyntaxKind.GreaterThanExpression or SyntaxKind.GreaterThanOrEqualExpression;

      private static bool InLoopCondition(SyntaxNode node)
         => node.Ancestors().OfType<ForStatementSyntax>().Any(f => f.Condition != null && f.Condition.Span.Contains(node.Span))
            || node.Ancestors().OfType<WhileStatementSyntax>().Any(w => w.Condition.Span.Contains(node.Span));

      /// <summary>A numeric literal (signed, parenthesised) that can be a threshold: not 0, 1 or -1, not an epsilon under 0.01.</summary>
      private static bool IsDecisionNumber(SyntaxNode node)
      {
         bool negative = false;
         while (true)
         {
            if (node is ParenthesizedExpressionSyntax paren) node = paren.Expression;
            else if (node is PrefixUnaryExpressionSyntax unary && unary.IsKind(SyntaxKind.UnaryMinusExpression))
            {
               negative = !negative;
               node = unary.Operand;
            }
            else break;
         }

         if (!(node is LiteralExpressionSyntax literal) || !literal.IsKind(SyntaxKind.NumericLiteralExpression)) return false;

         string digits = literal.Token.Text.TrimEnd('f', 'F', 'd', 'D', 'm', 'M', 'L', 'l', 'u', 'U');
         if (!double.TryParse(digits, NumberStyles.Float, CultureInfo.InvariantCulture, out double value)) return false;
         if (negative) value = -value;

         return Math.Abs(value) >= 0.01 && value != 0 && value != 1 && value != -1;
      }

      /// <summary>A fact read off an object: a member access (not Count or Length), or a call to a method named Get...</summary>
      private static bool ReadsAFact(SyntaxNode node)
      {
         while (true)
         {
            if (node is ParenthesizedExpressionSyntax paren) node = paren.Expression;
            else if (node is CastExpressionSyntax cast) node = cast.Expression;
            else if (node is PostfixUnaryExpressionSyntax bang && bang.IsKind(SyntaxKind.SuppressNullableWarningExpression)) node = bang.Operand;
            else break;
         }

         switch (node)
         {
            case MemberAccessExpressionSyntax access:
               return !NotAFact.Contains(access.Name.Identifier.Text, StringComparer.Ordinal);
            case ConditionalAccessExpressionSyntax conditional:
               return conditional.WhenNotNull is MemberBindingExpressionSyntax binding
                      ? !NotAFact.Contains(binding.Name.Identifier.Text, StringComparer.Ordinal)
                      : ReadsAFact(conditional.WhenNotNull);
            case MemberBindingExpressionSyntax binding2:
               return !NotAFact.Contains(binding2.Name.Identifier.Text, StringComparer.Ordinal);
            case BinaryExpressionSyntax coalesce when coalesce.IsKind(SyntaxKind.CoalesceExpression):
               return ReadsAFact(coalesce.Left);
            case InvocationExpressionSyntax call:
               string name = call.Expression switch {
                  MemberAccessExpressionSyntax m => m.Name.Identifier.Text,
                  MemberBindingExpressionSyntax b => b.Name.Identifier.Text,
                  IdentifierNameSyntax i => i.Identifier.Text,
                  _ => ""
               };
               return name.StartsWith("Get", StringComparison.Ordinal);
            default:
               return false;
         }
      }

      private static string MemberName(MemberDeclarationSyntax member) => member switch {
         MethodDeclarationSyntax m => m.Identifier.Text,
         PropertyDeclarationSyntax p => p.Identifier.Text,
         ConstructorDeclarationSyntax c => c.Identifier.Text,
         FieldDeclarationSyntax f => f.Declaration.Variables.FirstOrDefault()?.Identifier.Text,
         IndexerDeclarationSyntax => "this[]",
         OperatorDeclarationSyntax o => "operator " + o.OperatorToken.Text,
         _ => null
      };

      #endregion
   }
}

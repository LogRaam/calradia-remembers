   internal static class RegardDecisionsMap
   {
      public const string Path = "docs/maps/decisions-regard.md";

      private const int Step = 5;

      /// <summary>A parameter this map is willing to sweep: one number, on one of the two -100..100 scales.</summary>
      private static readonly string[] RegardParameterNames = {"regard", "relation", "reputation"};

      public static string Generate()
      {
         List<Decision> decisions = DecisionsOf(typeof(RegardBands).Assembly)
                                   .Concat(DecisionsOf(typeof(HushMoneyPolicy).Assembly))
                                   .OrderBy(d => d.Owner, StringComparer.Ordinal)
                                   .ThenBy(d => d.Name, StringComparer.Ordinal)
                                   .ToList();

         var sb = new StringBuilder();
         sb.AppendLine("# Decisions by regard: what every rung of the scale actually decides");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("Every cell is a REAL CALL into a real policy, swept from -100 to +100. Only rules that read a regard value");
         sb.AppendLine("and nothing else can appear: a decision that also weighs traits, distance or a die roll is not a function of");
         sb.AppendLine("the scale alone, and would need its own table.");
         sb.AppendLine();
         sb.AppendLine("**Two scales, not one.** `NpcProfile.ReputationWithPlayer` is the mod's own regard, built in conversation;");
         sb.AppendLine("`Hero.GetRelation` is vanilla's. Both are ints from -100 to 100 and the code calls both \"regard\" in places, so");
         sb.AppendLine("each column below says which one its rule was written for. `?` means the rule's own doc never says, which is");
         sb.AppendLine("the thing worth fixing.");
         sb.AppendLine();
         sb.AppendLine($"{decisions.Count} rules. A CHANGED CELL in this file is a changed behaviour: that is what makes this the safety");
         sb.AppendLine("net for giving regard a type and its tiers one home (see `ROADMAP.md`).");
         sb.AppendLine();

         AppendLegend(sb, decisions);
         AppendTable(sb, decisions);
         AppendBoundaries(sb, decisions);
         AppendWhatIsMissing(sb, decisions.Count);
         AppendInlineComparisons(sb);

         return sb.ToString();
      }

      #region private

      private sealed record Decision(string Owner, string Name, string Ledger, string Summary, Func<int, string> At);

      private static void AppendLegend(StringBuilder sb, List<Decision> decisions)
      {
         sb.AppendLine("## The rules in this table");
         sb.AppendLine();
         sb.AppendLine("| # | Rule | Ledger | What it decides |");
         sb.AppendLine("|---|---|---|---|");

         for (var i = 0; i < decisions.Count; i++)
            sb.AppendLine($"| {i + 1} | `{decisions[i].Owner}.{decisions[i].Name}` | {decisions[i].Ledger} | {DocText.Cell(decisions[i].Summary)} |");

         sb.AppendLine();
      }

      private static void AppendTable(StringBuilder sb, List<Decision> decisions)
      {
         sb.AppendLine("## The scale");
         sb.AppendLine();
         sb.AppendLine("Columns are numbered as in the table above.");
         sb.AppendLine();
         sb.AppendLine("| Regard | " + string.Join(" | ", Enumerable.Range(1, decisions.Count)) + " |");
         sb.AppendLine("|---" + string.Concat(Enumerable.Repeat("|---", decisions.Count)) + "|");

         for (int value = -100; value <= 100; value += Step)
            sb.AppendLine($"| **{value:+#;-#;0}** | " + string.Join(" | ", decisions.Select(d => DocText.Cell(d.At(value)))) + " |");

         sb.AppendLine();
      }

      /// <summary>Where each rule's answer CHANGES: the rungs of the scale, read off the behaviour rather than off the constants.</summary>
      private static void AppendBoundaries(StringBuilder sb, List<Decision> decisions)
      {
         sb.AppendLine("## Where each rule turns");
         sb.AppendLine();
         sb.AppendLine("The exact value (swept one point at a time) at which each answer changes. Rules that turn at the SAME value are");
         sb.AppendLine("candidates for one shared tier; rules that turn one or two points apart are worth a second look, since a gap that");
         sb.AppendLine("narrow is rarely a decision anybody made.");
         sb.AppendLine();
         sb.AppendLine("| Rule | Turns at |");
         sb.AppendLine("|---|---|");

         foreach (Decision decision in decisions)
         {
            var turns = new List<string>();

            for (var value = -99; value <= 100; value++)
               if (decision.At(value) != decision.At(value - 1))
                  turns.Add($"{value:+#;-#;0} ({DocText.Cell(decision.At(value - 1))} to {DocText.Cell(decision.At(value))})");

            sb.AppendLine($"| `{decision.Owner}.{decision.Name}` | {(turns.Count == 0 ? "never" : string.Join("; ", turns))} |");
         }

         sb.AppendLine();
      }

      /// <summary>
      ///   The measure of how much of the scale is NOT in this table, and why. A decision that is a FUNCTION can be
      ///   swept; a decision written inline as `x >= SomeThreshold` cannot, because there is nothing to call. The gap
      ///   between the two counts is the size of the "fetch the value and compare it yourself" habit, and it should
      ///   shrink as regard becomes a type that answers questions.
      /// </summary>
      private static void AppendWhatIsMissing(StringBuilder sb, int swept)
      {
         List<string> thresholds = RegardThresholds().ToList();

         sb.AppendLine("## What this table does not show yet, and why");
         sb.AppendLine();
         sb.AppendLine($"{swept} rules can be swept here. Against that, the code declares **{thresholds.Count} regard-named thresholds**");
         sb.AppendLine("(constants whose name carries regard, relation or reputation). The difference is the gap: those thresholds are");
         sb.AppendLine("compared INLINE, at the place that wants the answer, so there is no function to call and nothing to sweep.");
         sb.AppendLine();
         sb.AppendLine("That gap is the thing to close, and closing it is what makes the rest of the scale measurable: a decision asked");
         sb.AppendLine("of the value (`regard.IsFriend`) can be swept; a decision taken about the value (`regard >= FriendThreshold`)");
         sb.AppendLine("cannot. Each one moved into a rule adds a column here.");
         sb.AppendLine();
         sb.AppendLine("<details><summary>The thresholds not yet represented</summary>");
         sb.AppendLine();

         foreach (string threshold in thresholds) sb.AppendLine($"- `{threshold}`");

         sb.AppendLine();
         sb.AppendLine("</details>");
         sb.AppendLine();
      }

      /// <summary>
      ///   The members that ARE the two ledgers: reading one of these is reading regard, whatever the surrounding code
      ///   calls it. The fact the name-based list above cannot see (26/09/2026).
      /// </summary>
      private static readonly string[] LedgerMembers = {"ReputationWithPlayer", "GetRelation", "RelationToPlayer", "RegardForPlayer", "RegardTowardPlayer"};

      /// <summary>
      ///   THE SILENT GAP IN THE LIST ABOVE (Gabriel, 26/09/2026: "une carte qui se trompe silencieusement, parce
      ///   qu'un nom ment"). That list finds a threshold by the NAME of a constant, so a rung compared inline with no
      ///   constant at all (`regards.Average() &lt; 0`, found in TrialVerdictPolicy the day this was written) is
      ///   invisible to it, and to the ratchet that counts it. This reads what the code COMPARES instead: every
      ///   comparison between a bare number and a value read off a ledger member, or a value named for regard.
      ///   Listed by owner and member, never by line, so an unrelated edit above does not churn the map.
      /// </summary>
      private static void AppendInlineComparisons(StringBuilder sb)
      {
         List<string> found = InlineRegardComparisons().ToList();

         sb.AppendLine("## Regard compared inline against a bare number");
         sb.AppendLine();
         sb.AppendLine($"**{found.Count} comparisons** read a regard value and compare it with a number written in place, no named");
         sb.AppendLine("constant at all. The list above cannot see these: it finds thresholds by the NAME of a constant, and there is");
         sb.AppendLine("none. Found by what the code compares: one side reads a ledger member (" + string.Join(", ", LedgerMembers.Select(m => $"`{m}`")) + ")");
         sb.AppendLine("or a value named for regard, relation or reputation; the other side is a number.");
         sb.AppendLine();
         sb.AppendLine("<details><summary>The inline comparisons</summary>");
         sb.AppendLine();

         foreach (string comparison in found) sb.AppendLine($"- {comparison}");

         sb.AppendLine();
         sb.AppendLine("</details>");
         sb.AppendLine();
      }

      /// <summary>Every inline comparison of a regard value with a bare number, as `Owner.Member`: `expression`.</summary>
      internal static IEnumerable<string> InlineRegardComparisons()
      {
         if (!SourceTree.IsReachable) yield break;

         var seen = new SortedSet<string>(StringComparer.Ordinal);

         foreach (SourceFile file in SourceTree.Production)
            foreach (var binary in file.Root.DescendantNodes().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.BinaryExpressionSyntax>())
            {
               if (!IsComparison(binary)) continue;

               bool leftNumber = IsBareNumber(binary.Left), rightNumber = IsBareNumber(binary.Right);
               if (leftNumber == rightNumber) continue; // two numbers, or no number: not a threshold

               Microsoft.CodeAnalysis.SyntaxNode read = leftNumber ? binary.Right : binary.Left;
               string how = ReadsRegard(read);
               if (how == null) continue;
               if (PicksASignToPrint(binary)) continue;

               string owner = binary.Ancestors().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.BaseTypeDeclarationSyntax>().FirstOrDefault()?.Identifier.Text ?? "?";
               string member = binary.Ancestors().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.MemberDeclarationSyntax>()
                                     .Select(MemberName).FirstOrDefault(n => n != null) ?? "?";
               string expression = System.Text.RegularExpressions.Regex.Replace(binary.ToString(), @"\s+", " ");

               seen.Add($"`{owner}.{member}`: `{expression}` ({how})");
            }

         foreach (string entry in seen) yield return entry;
      }

      /// <summary>
      ///   A comparison with zero whose only use is to choose between two strings (<c>regard >= 0 ? "+" : ""</c>):
      ///   it prints a sign, it decides nothing about the character. Found 26/09/2026 when the two FormatRegard
      ///   helpers were the last "thresholds" left once every real one pointed at a rung.
      /// </summary>
      private static bool PicksASignToPrint(Microsoft.CodeAnalysis.CSharp.Syntax.BinaryExpressionSyntax binary)
      {
         Microsoft.CodeAnalysis.SyntaxNode number = IsBareNumber(binary.Left) ? binary.Left : binary.Right;
         if (number.ToString().Trim() != "0") return false;

         Microsoft.CodeAnalysis.SyntaxNode node = binary;
         while (node.Parent is Microsoft.CodeAnalysis.CSharp.Syntax.ParenthesizedExpressionSyntax) node = node.Parent;

         return node.Parent is Microsoft.CodeAnalysis.CSharp.Syntax.ConditionalExpressionSyntax conditional
                && conditional.Condition == node
                && IsText(conditional.WhenTrue) && IsText(conditional.WhenFalse);
      }

      private static bool IsText(Microsoft.CodeAnalysis.SyntaxNode node)
         => node.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.StringLiteralExpression)
            || node.ToString() is "string.Empty" or "String.Empty";

      private static bool IsComparison(Microsoft.CodeAnalysis.CSharp.Syntax.BinaryExpressionSyntax binary)
         => binary.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.LessThanExpression)
         || binary.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.LessThanOrEqualExpression)
         || binary.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.GreaterThanExpression)
         || binary.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.GreaterThanOrEqualExpression)
         || binary.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.EqualsExpression)
         || binary.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.NotEqualsExpression);

      /// <summary>A numeric literal, signed or not (`-20`, `0`, `5f`).</summary>
      private static bool IsBareNumber(Microsoft.CodeAnalysis.SyntaxNode node)
      {
         if (node is Microsoft.CodeAnalysis.CSharp.Syntax.PrefixUnaryExpressionSyntax unary) node = unary.Operand;
         if (node is Microsoft.CodeAnalysis.CSharp.Syntax.ParenthesizedExpressionSyntax paren) node = paren.Expression;

         return node is Microsoft.CodeAnalysis.CSharp.Syntax.LiteralExpressionSyntax literal
                && literal.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.NumericLiteralExpression);
      }

      /// <summary>
      ///   Names that carry regard in their name but hold a CHANGE to it (a reward, a hit, a nudge, a shift) or a
      ///   derived tier, never a point on the scale: a sign test on them is not a rung. The fallback's own filter.
      /// </summary>
      private static readonly string[] NotAPointOnTheScale = {"Reward", "Hit", "Nudge", "Shift", "Delta", "Change", "Tier", "Resistance"};

      /// <summary>
      ///   How the expression reads regard, or null when it does not: "ledger" when it names one of the two ledgers'
      ///   own members (a fact), "named" when only an identifier NAMED for regard, relation or reputation says so (the
      ///   fallback for a value carried in a local, such as a list of regards; name-based, so it can be wrong in both
      ///   directions, and is marked as such). A count or length of such a collection is not a regard.
      /// </summary>
      private static string? ReadsRegard(Microsoft.CodeAnalysis.SyntaxNode node)
      {
         if (node is Microsoft.CodeAnalysis.CSharp.Syntax.MemberAccessExpressionSyntax access
             && access.Name.Identifier.Text is "Count" or "Length")
            return null;

         var ids = node.DescendantNodesAndSelf().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.IdentifierNameSyntax>()
                       .Select(id => id.Identifier.Text).ToList();

         if (ids.Any(name => LedgerMembers.Contains(name, StringComparer.Ordinal))) return "ledger";

         bool named = ids.Any(name => RegardParameterNames.Any(n => name.Contains(n, StringComparison.OrdinalIgnoreCase))
                                      && !NotAPointOnTheScale.Any(x => name.Contains(x, StringComparison.OrdinalIgnoreCase)));

         return named ? "named" : null;
      }

      private static string? MemberName(Microsoft.CodeAnalysis.CSharp.Syntax.MemberDeclarationSyntax member) => member switch
      {
         Microsoft.CodeAnalysis.CSharp.Syntax.MethodDeclarationSyntax m => m.Identifier.Text,
         Microsoft.CodeAnalysis.CSharp.Syntax.PropertyDeclarationSyntax p => p.Identifier.Text,
         Microsoft.CodeAnalysis.CSharp.Syntax.ConstructorDeclarationSyntax c => c.Identifier.Text,
         Microsoft.CodeAnalysis.CSharp.Syntax.FieldDeclarationSyntax f => f.Declaration.Variables.FirstOrDefault()?.Identifier.Text,
         _ => null
      };

      /// <summary>Every numeric constant whose NAME says it is a point on one of the two scales.</summary>
      private static IEnumerable<string> RegardThresholds()
      {
         if (!SourceTree.IsReachable) yield break;

         var seen = new SortedSet<string>(StringComparer.Ordinal);

         foreach (SourceFile file in SourceTree.Production)
            foreach (var field in file.Root.DescendantNodes().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.FieldDeclarationSyntax>())
            {
               if (!field.Modifiers.Any(m => m.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.ConstKeyword))) continue;
               if (field.Declaration.Type.ToString() != "int") continue;

               string owner = field.Ancestors().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.BaseTypeDeclarationSyntax>().FirstOrDefault()?.Identifier.Text ?? "";

               foreach (var variable in field.Declaration.Variables)
               {
                  string name = variable.Identifier.Text;
                  if (!RegardParameterNames.Any(n => name.Contains(n, StringComparison.OrdinalIgnoreCase))) continue;

                  seen.Add($"{owner}.{name} = {variable.Initializer?.Value}");
               }
            }

         foreach (string entry in seen) yield return entry;
      }

      /// <summary>
      ///   Every public static method of the assembly that takes ONE regard-like number and, apart from it, only
      ///   parameters with defaults. Anything else is not a function of the scale alone.
      /// </summary>
      private static IEnumerable<Decision> DecisionsOf(Assembly assembly)
      {
         foreach (Type type in assembly.GetTypes().Where(t => t.IsPublic && !t.IsNested))
            foreach (MethodInfo method in type.GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
               ParameterInfo[] parameters = method.GetParameters();
               ParameterInfo? sweepable = parameters.FirstOrDefault(IsRegardParameter);

               if (sweepable == null) continue;
               if (parameters.Any(p => p != sweepable && !p.IsOptional)) continue;
               if (method.ReturnType == typeof(void)) continue;

               MethodInfo captured = method;
               ParameterInfo capturedSweep = sweepable;

               yield return new Decision(type.Name, method.Name, LedgerOf(type, method),
                  SummaryOf(type, method), value => Invoke(captured, capturedSweep, value));
            }
      }

      /// <summary>
      ///   A parameter this map sweeps: one of the two ledger TYPES (a fact: the compiler holds every caller to it), or
      ///   a plain int NAMED for regard, relation or reputation that is not a change to it (a reward, a hit).
      /// </summary>
      private static bool IsRegardParameter(ParameterInfo parameter)
         => parameter.ParameterType == typeof(Regard)
         || parameter.ParameterType == typeof(VanillaRelation)
         || (parameter.ParameterType == typeof(int)
             && RegardParameterNames.Any(n => parameter.Name?.Contains(n, StringComparison.OrdinalIgnoreCase) == true)
             && !NotAPointOnTheScale.Any(x => parameter.Name?.Contains(x, StringComparison.OrdinalIgnoreCase) == true));

      private static string Invoke(MethodInfo method, ParameterInfo sweep, int value)
      {
         object swept = sweep.ParameterType == typeof(Regard) ? new Regard(value)
                      : sweep.ParameterType == typeof(VanillaRelation) ? new VanillaRelation(value)
                      : value;
         object?[] arguments = method.GetParameters()
                                     .Select(p => p == sweep ? swept : p.HasDefaultValue ? p.DefaultValue : null)
                                     .ToArray();

         try
         {
            object? result = method.Invoke(null, arguments);

            return result switch {
               null => "null",
               bool flag => flag ? "yes" : "no",
               _ => result.ToString() ?? ""
            };
         }
         catch (Exception ex)
         {
            // A rule that throws on part of the scale is worth SEEING, not hiding: it is a gap in what it accepts.
            return "throws " + (ex.InnerException ?? ex).GetType().Name;
         }
      }

      /// <summary>
      ///   Which ledger the rule reads, from what it says about itself. A doc that names ReputationWithPlayer means the
      ///   mod's own; one that names GetRelation or "vanilla" means the engine's. Most say neither, and that is the
      ///   finding, not a shortcoming of this map.
      /// </summary>
      /// <summary>
      ///   Which ledger the rule reads, and HOW that is known (Gabriel, 26/09/2026: a map that mixes detection modes
      ///   says, per line, which produced it). From the parameter's TYPE when it is <see cref="Regard" /> or
      ///   <see cref="VanillaRelation" />: a fact the compiler enforces on every caller. Otherwise from what the doc
      ///   says, which is only text, and "?" when it says nothing.
      /// </summary>
      private static string LedgerOf(Type type, MethodInfo method)
      {
         ParameterInfo? typed = method.GetParameters().FirstOrDefault(p => p.ParameterType == typeof(Regard) || p.ParameterType == typeof(VanillaRelation));
         if (typed != null) return typed.ParameterType == typeof(Regard) ? "mod (type)" : "vanilla (type)";

         // The WHOLE doc, not its first sentence (26/09/2026: a ledger named past the first sentence was silently
         // missed, the second silent error the maps showed that day).
         string text = (DocOf(type, method, whole: true) + " " + DocOf(type, null, whole: true)).ToLowerInvariant();

         bool mod = text.Contains("reputationwithplayer") || text.Contains("personal regard") || text.Contains("mod's own");
         bool vanilla = text.Contains("getrelation") || text.Contains("vanilla relation") || text.Contains("engine relation");

         return mod && vanilla ? "both named (doc)" : mod ? "mod (doc)" : vanilla ? "vanilla (doc)" : "?";
      }

      private static string SummaryOf(Type type, MethodInfo method)
      {
         string own = DocOf(type, method);

         return own.Length > 0 ? own : DocOf(type, null);
      }

      /// <summary>
      ///   The doc comment for a type or a method, read from the SOURCE (the compiler drops them from the assembly,
      ///   and the XML file beside it is not guaranteed to be there).
      /// </summary>
      private static string DocOf(Type type, MethodInfo? method, bool whole = false)
      {
         if (!SourceTree.IsReachable) return "";

         foreach (SourceFile file in SourceTree.Production)
         {
            var declaration = file.Root.DescendantNodes()
                                  .OfType<Microsoft.CodeAnalysis.CSharp.Syntax.BaseTypeDeclarationSyntax>()
                                  .FirstOrDefault(t => t.Identifier.Text == type.Name);

            if (declaration == null) continue;

            if (method == null) return whole ? DocText.AllOf(declaration) : DocText.FirstSentenceOf(declaration);

            var declared = declaration.DescendantNodes()
                                      .OfType<Microsoft.CodeAnalysis.CSharp.Syntax.MethodDeclarationSyntax>()
                                      .FirstOrDefault(m => m.Identifier.Text == method.Name);

            if (declared != null) return whole ? DocText.AllOf(declared) : DocText.FirstSentenceOf(declared);
         }

         return "";
      }

      #endregion
   }

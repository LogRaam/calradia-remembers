// Code written by Gabriel Mailhot, 21/09/2026.
// docs/maps/decisions-regard.md: the regard scale from -100 to +100, and what every pure rule that reads nothing else
// DECIDES at each rung. One page, read in two minutes.
//
// The other maps list declarations. This one runs the code: each cell is a real call into a real policy, so the table
// cannot describe a system the game does not have. It exists for two reasons.
//
//   1. It is the view Gabriel asked for. constants.md is complete and 2850 lines long; nobody reads a threshold list
//      to understand a scale. Here the rungs line up in one column and the gaps are visible: a hero the prompt calls
//      "a friend" at 12 who feels no gratitude and receives no letter is one glance, not a five-file investigation.
//   2. It is the safety net for the work that follows. Turning regard into a type, and giving the tiers one home, must
//      not move a single decision. Every step of that refactor is measured here: if a cell changes, a behaviour
//      changed with it, and the suite says so before a player does.
//
// THE TWO LEDGERS ARE SHOWN SIDE BY SIDE ON PURPOSE. NpcProfile.ReputationWithPlayer (the mod's own, built in
// conversation) and Hero.GetRelation (vanilla) are both ints from -100 to 100, both called "regard" or "relation"
// half the time, and a policy's own doc often does not say which it reads. Until they are two types, this table is
// where that confusion is at least VISIBLE: each column says which ledger its rule was written for, or says it is
// unstated.


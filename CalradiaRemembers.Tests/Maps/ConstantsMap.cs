// two questions and not a duplicate. This map puts them side by side, so the next one is seen as it is born.

#region

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class ConstantsMap
   {
      public const string Path = "docs/maps/constants.md";

      private static readonly HashSet<string> NumericTypes = new() {"int", "double", "float", "long", "decimal", "short", "byte", "uint"};

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<Constant> all = ConstantsOf(files);
         var sb = new StringBuilder();

         sb.AppendLine("# Constants: every number the system is tuned by");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine($"{all.Count} numeric constants in {all.Select(c => c.Owner).Distinct().Count()} types. Look here BEFORE adding a threshold: if the");
         sb.AppendLine("concept has a name already, the first section shows every place that name lives and what each is worth.");
         sb.AppendLine();

         AppendSharedNames(sb, all);
         AppendByOwner(sb, all);

         return sb.ToString();
      }

      #region private

      private sealed record Constant(Layer Layer, string Owner, string Name, string Value, string Summary);

      private static List<Constant> ConstantsOf(IReadOnlyList<SourceFile> files)
      {
         var found = new List<Constant>();

         foreach (SourceFile file in files)
            foreach (FieldDeclarationSyntax field in file.Root.DescendantNodes().OfType<FieldDeclarationSyntax>())
            {
               if (!field.Modifiers.Any(m => m.IsKind(SyntaxKind.ConstKeyword))) continue;
               if (!NumericTypes.Contains(field.Declaration.Type.ToString())) continue;

               string owner = field.Ancestors().OfType<BaseTypeDeclarationSyntax>().FirstOrDefault()?.Identifier.Text ?? "(none)";
               string summary = DocText.FirstSentenceOf(field);

               foreach (VariableDeclaratorSyntax variable in field.Declaration.Variables)
                  found.Add(new Constant(file.Layer, owner, variable.Identifier.Text,
                     variable.Initializer?.Value.ToString() ?? "?", summary));
            }

         return found;
      }

      /// <summary>The doublon lens: one NAME declared in several types. Same value or not, it is one concept spelled more than once.</summary>
      private static void AppendSharedNames(StringBuilder sb, List<Constant> all)
      {
         List<IGrouping<string, Constant>> shared = all.GroupBy(c => c.Name)
                                                       .Where(g => g.Select(c => c.Owner).Distinct().Count() > 1)
                                                       .OrderBy(g => g.Key, StringComparer.Ordinal)
                                                       .ToList();

         sb.AppendLine("## One name, several homes");
         sb.AppendLine();
         sb.AppendLine("The same constant NAME declared in more than one type. Sometimes they are two honest questions that happen");
         sb.AppendLine("to share a word; sometimes it is one concept that should have one home. Either way it should be a decision.");
         sb.AppendLine();

         if (shared.Count == 0)
         {
            sb.AppendLine("None.");
            sb.AppendLine();

            return;
         }

         sb.AppendLine("| Name | Where, and what it is worth there |");
         sb.AppendLine("|---|---|");

         foreach (IGrouping<string, Constant> group in shared)
         {
            IEnumerable<string> homes = group.OrderBy(c => c.Owner, StringComparer.Ordinal).Select(c => $"`{c.Owner}` = {c.Value}");
            sb.AppendLine($"| `{group.Key}` | {DocText.Cell(string.Join("; ", homes))} |");
         }

         sb.AppendLine();
      }

      private static void AppendByOwner(StringBuilder sb, List<Constant> all)
      {
         foreach (Layer layer in Enum.GetValues<Layer>())
         {
            sb.AppendLine($"## {InventoryMap.LayerName(layer)}");
            sb.AppendLine();

            foreach (IGrouping<string, Constant> owner in all.Where(c => c.Layer == layer)
                                                             .GroupBy(c => c.Owner)
                                                             .OrderBy(g => g.Key, StringComparer.Ordinal))
            {
               sb.AppendLine($"### {owner.Key}");
               sb.AppendLine();
               sb.AppendLine("| Constant | Value | What it is |");
               sb.AppendLine("|---|---|---|");

               foreach (Constant constant in owner.OrderBy(c => c.Name, StringComparer.Ordinal))
                  sb.AppendLine($"| `{constant.Name}` | {DocText.Cell(constant.Value)} | {DocText.Cell(constant.Summary)} |");

               sb.AppendLine();
            }
         }
      }

      #endregion
   }
}

// RULES.md and docs/maps/rules-sdk.md: everything the system promises to do, as its own tests state it.
//
// This one already existed. Tools/Generate-Rules.ps1 wrote RULES.md from the test names (Gabriel, 10/09/2026: "je peux
// mieux comprendre la logique implementee car les tests expriment des regles du mod"), and its own header said
// "Regenerate it whenever the suite changes". Nobody did: on 21/09 it was ten days and some six hundred rules behind,
// which is the whole case for a trigger in one example. The generator now lives here, where a test runs it on every
// change; the script remains only as a viewer (-Filter) and as a shortcut to regenerate.
//
// A behaviour change leaves no structural trace, so no structural map will ever show it. But a behaviour that matters
// is held by a test, named GIVEN/WHEN/THEN with its stake, so it shows HERE. What still stays invisible after that is
// a behaviour that changed with no test changing, which is not a gap in the maps: it is a missing test.

#region

using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class RulesMap
   {
      public const string ModPath = "RULES.md";
      public const string SdkPath = "docs/maps/rules-sdk.md";

      private static readonly string[] TestAttributes = {"Test", "TestCase", "TestCaseSource", "Theory"};

      public static string GenerateForMod(IReadOnlyList<SourceFile> testFiles)
         => Generate(testFiles, "# Calradia Remembers: the rules, as its own tests state them");

      public static string GenerateForSdk(IReadOnlyList<SourceFile> testFiles)
         => Generate(testFiles, "# LLM Roleplay Service (the SDK): the rules, as its own tests state them");

      #region private

      private sealed record Fixture(string Path, string Purpose, List<string> Rules);

      private static string Generate(IReadOnlyList<SourceFile> testFiles, string title)
      {
         var sections = new SortedDictionary<string, List<Fixture>>(StringComparer.Ordinal);
         var ruleCount = 0;
         var unnamedCount = 0;
         var fixtureCount = 0;

         foreach (SourceFile file in testFiles)
         {
            List<string> names = TestNamesIn(file);
            if (names.Count == 0) continue;

            fixtureCount++;

            var rules = new List<string>();
            foreach (string name in names)
               if (name.StartsWith("GIVEN_", StringComparison.Ordinal))
               {
                  rules.Add(Sentence(name));
                  ruleCount++;
               }
               else
               {
                  rules.Add("(not stated as a rule) " + Sentence(name));
                  unnamedCount++;
               }

            string group = file.RelativePath.Contains('/') ? file.RelativePath.Split('/')[0] : "General";
            if (!sections.ContainsKey(group)) sections[group] = new List<Fixture>();
            sections[group].Add(new Fixture(file.RelativePath, PurposeOf(file.Text), rules));
         }

         var sb = new StringBuilder();
         sb.AppendLine(title);
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit: every line is lifted from a");
         sb.AppendLine("test name and a test file's header, so this cannot drift from the behaviour it describes, and a test fails when");
         sb.AppendLine("this file no longer matches the suite. See `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine($"{ruleCount} rules across {fixtureCount} fixtures. A line marked `(not stated as a rule)` is a");
         sb.AppendLine("test whose name describes a return value or a branch rather than something anyone would");
         sb.AppendLine("notice; those are shown rather than hidden, because a gap in a specification should be");
         sb.AppendLine($"visible. There are {unnamedCount} of them. See CLAUDE.md, \"What a test is for\".");
         sb.AppendLine();

         foreach ((string group, List<Fixture> fixtures) in sections)
         {
            sb.AppendLine($"## {group}");
            sb.AppendLine();

            foreach (Fixture fixture in fixtures.OrderBy(f => f.Path, StringComparer.Ordinal))
            {
               sb.AppendLine($"### {fixture.Path}");
               sb.AppendLine();
               if (fixture.Purpose.Length > 0)
               {
                  sb.AppendLine($"_{fixture.Purpose}_");
                  sb.AppendLine();
               }

               foreach (string rule in fixture.Rules) sb.AppendLine($"- {rule}");
               sb.AppendLine();
            }
         }

         return sb.ToString();
      }

      /// <summary>Only what a runner would execute: the old script matched every `public void`, SetUp and TearDown included.</summary>
      private static List<string> TestNamesIn(SourceFile file)
         => file.Root.DescendantNodes().OfType<MethodDeclarationSyntax>()
                .Where(m => m.AttributeLists.SelectMany(l => l.Attributes)
                             .Any(a => TestAttributes.Contains(a.Name.ToString().Replace("Attribute", ""))))
                .Select(m => m.Identifier.Text)
                .ToList();

      /// <summary>GIVEN_a_lord_WHEN_asked_THEN_he_rides becomes "GIVEN a lord, WHEN asked, THEN he rides".</summary>
      private static string Sentence(string name)
      {
         string text = name.Replace('_', ' ');
         text = Regex.Replace(text, @"\bWHEN\b", ", WHEN");
         text = Regex.Replace(text, @"\bTHEN\b", ", THEN");
         text = Regex.Replace(text, @"\s+", " ");
         text = Regex.Replace(text, @"\s+,", ",");

         return text.Trim();
      }

      /// <summary>
      ///   The one line of a file header worth carrying: why the fixture exists. Its own "What this pins" /
      ///   "What these pin" sentence when it has one, else the first real sentence after the authorship line,
      ///   carried across the wrapped lines it was written on so it never stops mid-clause.
      /// </summary>
      private static string PurposeOf(string text)
      {
         List<string> header = text.Replace("\r\n", "\n").Split('\n')
                                   .TakeWhile(l => Regex.IsMatch(l, @"^\s*//"))
                                   .Select(l => Regex.Replace(l, @"^\s*//\s?", ""))
                                   .ToList();

         if (header.Count == 0) return "";

         for (var i = 0; i < header.Count; i++)
         {
            Match pins = Regex.Match(header[i], @"What (?:this pins|these pin):\s*(.*)");
            if (!pins.Success) continue;

            string sentence = pins.Groups[1].Value;
            for (int j = i + 1; j < header.Count && header[j].Trim().Length > 0 && !Regex.IsMatch(sentence, @"\.\s*$"); j++)
               sentence = $"{sentence} {header[j].Trim()}";

            return sentence.Trim();
         }

         var first = "";
         foreach (string line in header)
         {
            string t = line.Trim();
            if (first.Length == 0 && (t.Length == 0 || t.StartsWith("Code written by", StringComparison.Ordinal))) continue;
            if (t.Length == 0) break;

            first = first.Length == 0 ? t : $"{first} {t}";
            if (Regex.IsMatch(first, @"\.\s*$")) break;
         }

         return first.Trim();
      }

      #endregion
   }
}

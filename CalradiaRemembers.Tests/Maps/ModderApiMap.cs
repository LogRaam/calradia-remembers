// The second CONTRACT. tashmetu's Bellum Bridge is built on CrPrompt.RegisterVariable and cr_patch, and every one of
// the four 2.5.15 fixes and the 2.5.19 threading fix came from him reading that surface from outside. A signature
// changed here is not a refactor: it is somebody else's mod failing to load on a player's machine, reported to them
// and not to us. With the surface written down one member per line, a breaking change is a removed or altered line in a
// diff, seen in the commit that makes it, instead of a bug report three days later.
//
// The surface is what lives under an `Extension` folder in the mod and in the SDK. Anything public elsewhere is public
// by accident of C#, not by promise.

#region

using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class ModderApiMap
   {
      public const string Path = "docs/maps/modder-api.md";

      private const string SurfaceFolder = "Extension/";

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<SourceFile> surface = files.Where(f => f.RelativePath.StartsWith(SurfaceFolder, StringComparison.Ordinal)).ToList();
         var sb = new StringBuilder();

         sb.AppendLine("# Modder API: the public surface other mods are built against");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("**This is a contract with other people's mods.** A line ADDED here is a new capability. A line REMOVED or");
         sb.AppendLine("CHANGED is a breaking change for every bridge already shipped, and belongs in the release notes under \"For");
         sb.AppendLine("modders\", with the version it happened in. The surface is everything public under an `Extension` folder.");
         sb.AppendLine();

         foreach (Layer layer in new[] {Layer.Mod, Layer.Sdk})
         {
            sb.AppendLine($"## {InventoryMap.LayerName(layer)}");
            sb.AppendLine();

            foreach (BaseTypeDeclarationSyntax type in surface.Where(f => f.Layer == layer)
                                                              .SelectMany(f => f.Root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
                                                              .Where(IsPublic)
                                                              .OrderBy(t => t.Identifier.Text, StringComparer.Ordinal))
            {
               sb.AppendLine($"### {type.Identifier.Text}");
               sb.AppendLine();
               sb.AppendLine($"_{DocText.FirstSentenceOf(type)}_");
               sb.AppendLine();

               foreach (string line in MembersOf(type).OrderBy(l => l, StringComparer.Ordinal)) sb.AppendLine($"- `{line}`");

               sb.AppendLine();
            }
         }

         return sb.ToString();
      }

      #region private

      private static bool IsPublic(MemberDeclarationSyntax member) => member.Modifiers.Any(m => m.IsKind(SyntaxKind.PublicKeyword));

      private static string Modifiers(MemberDeclarationSyntax member)
      {
         string text = string.Join(" ", member.Modifiers.Where(m => m.IsKind(SyntaxKind.StaticKeyword) || m.IsKind(SyntaxKind.ConstKeyword)
                                                                 || m.IsKind(SyntaxKind.ReadOnlyKeyword) || m.IsKind(SyntaxKind.AbstractKeyword))
                                              .Select(m => m.Text));

         return text.Length == 0 ? "" : text + " ";
      }

      private static string Flat(SyntaxNode? node) => node == null ? "" : Regex.Replace(node.ToString(), @"\s+", " ").Trim();

      /// <summary>One line per public member, written the way a caller sees it: no bodies, no attributes, no comments.</summary>
      private static IEnumerable<string> MembersOf(BaseTypeDeclarationSyntax type)
      {
         if (type is EnumDeclarationSyntax enumeration)
         {
            foreach (EnumMemberDeclarationSyntax member in enumeration.Members)
               yield return $"{member.Identifier.Text}{(member.EqualsValue == null ? "" : " " + Flat(member.EqualsValue))}";

            yield break;
         }

         // An interface's members are public without saying so.
         bool allPublic = type is InterfaceDeclarationSyntax;

         foreach (MemberDeclarationSyntax member in ((TypeDeclarationSyntax) type).Members)
         {
            if (!allPublic && !IsPublic(member)) continue;

            switch (member)
            {
               case MethodDeclarationSyntax method:
                  yield return $"{Modifiers(method)}{Flat(method.ReturnType)} {method.Identifier.Text}{Flat(method.TypeParameterList)}{Flat(method.ParameterList)}";

                  break;
               case PropertyDeclarationSyntax property:
                  string accessors = property.AccessorList == null
                     ? "{ get; }"
                     : "{ " + string.Join(" ", property.AccessorList.Accessors
                                                       .Where(a => !a.Modifiers.Any(m => m.IsKind(SyntaxKind.PrivateKeyword) || m.IsKind(SyntaxKind.InternalKeyword)))
                                                       .Select(a => a.Keyword.Text + ";")) + " }";

                  yield return $"{Modifiers(property)}{Flat(property.Type)} {property.Identifier.Text} {accessors}";

                  break;
               case FieldDeclarationSyntax field:
                  foreach (VariableDeclaratorSyntax variable in field.Declaration.Variables)
                     yield return $"{Modifiers(field)}{Flat(field.Declaration.Type)} {variable.Identifier.Text}{(variable.Initializer == null ? "" : " " + Flat(variable.Initializer))}";

                  break;
               case EventFieldDeclarationSyntax @event:
                  foreach (VariableDeclaratorSyntax variable in @event.Declaration.Variables)
                     yield return $"{Modifiers(@event)}event {Flat(@event.Declaration.Type)} {variable.Identifier.Text}";

                  break;
               case ConstructorDeclarationSyntax constructor:
                  yield return $"{constructor.Identifier.Text}{Flat(constructor.ParameterList)}";

                  break;
               case DelegateDeclarationSyntax @delegate:
                  yield return $"delegate {Flat(@delegate.ReturnType)} {@delegate.Identifier.Text}{Flat(@delegate.ParameterList)}";

                  break;
            }
         }
      }

      #endregion
   }
}

// docs/maps/initiatives.md: every path where a character takes the initiative toward the player, and where it asks the
// one gate (NpcInitiativeGate: alive, of age, free, not the player).
//
// Gabriel, 30/09/2026, after a baby son asked to discuss warfare: every NPC action should pass common conditions, and
// fail to happen when they are not met. An inventory that day found about a dozen paths with a dozen filters, two of
// them checking age. The gate is the rule; this map is how its reach is SEEN: each kind, each place that asks for it,
// and every place that writes a letter straight into the post, with whether it asks. RatchetTests holds the two walls.

#region

using System.Text;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class InitiativesMap
   {
      public const string Path = "docs/maps/initiatives.md";

      private const string Gate = "InitiativeGate";

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<SourceFile> mod = GameFiles(files);
         var sb = new StringBuilder();

         sb.AppendLine("# Initiatives: where a character acts toward the player, and the gate each one asks");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("Every initiative asks `InitiativeGate` (the live side of `NpcInitiativeGate`): the character is alive, of age");
         sb.AppendLine("(`Hero.IsChild`, never a rank: `IsLord` is an occupation), free, and not the player. Each path keeps its own");
         sb.AppendLine("conditions on top. Answering the player (a reply), being the subject of news, and the verbs a model emits in");
         sb.AppendLine("conversation are not initiatives and have their own rules.");
         sb.AppendLine();
         sb.AppendLine("## By kind");
         sb.AppendLine();
         sb.AppendLine("| Kind | Asked in |");
         sb.AppendLine("|---|---|");
         foreach (IGrouping<string, (string Kind, string Site)> kind in KindSites(mod).GroupBy(k => k.Kind).OrderBy(g => g.Key, StringComparer.Ordinal))
            sb.AppendLine($"| `{kind.Key}` | {string.Join(", ", kind.Select(k => $"`{k.Site}`").Distinct().OrderBy(x => x, StringComparer.Ordinal))} |");

         sb.AppendLine();
         sb.AppendLine("## Letters written straight into the post");
         sb.AppendLine();
         sb.AppendLine("A letter added to a character's `SentLetters` outside the letter pipeline is an initiative the pipeline's own");
         sb.AppendLine("gate never saw; the file must ask the gate itself.");
         sb.AppendLine();
         sb.AppendLine("| File | Asks the gate |");
         sb.AppendLine("|---|---|");
         foreach ((string file, bool asks) in DirectLetterFiles(files))
            sb.AppendLine($"| `{file}` | {(asks ? "yes" : "**NO**")} |");

         sb.AppendLine();

         return sb.ToString();
      }

      /// <summary>Each InitiativeKind the game code names, with the Type.Method naming it.</summary>
      public static List<(string Kind, string Site)> KindSites(IReadOnlyList<SourceFile> files)
         => GameFiles(files)
            .SelectMany(f => f.Root.DescendantNodes().OfType<MemberAccessExpressionSyntax>()
                              .Where(m => m.Expression.ToString().EndsWith("InitiativeKind", StringComparison.Ordinal))
                              .Select(m => (m.Name.Identifier.Text, SiteOf(m))))
            .ToList();

      /// <summary>Every game file that adds a letter to SentLetters directly, and whether it asks the gate.</summary>
      public static List<(string File, bool AsksGate)> DirectLetterFiles(IReadOnlyList<SourceFile> files)
         => GameFiles(files)
            .Where(f => f.Root.DescendantNodes().OfType<InvocationExpressionSyntax>()
                         .Any(i => i.Expression is MemberAccessExpressionSyntax {Name.Identifier.Text: "Add"} m
                                   && m.Expression.ToString().EndsWith("SentLetters", StringComparison.Ordinal)))
            .Select(f => (f.RelativePath, f.Text.Contains(Gate + ".Allows") || f.Text.Contains(Gate + ".Check")))
            .OrderBy(x => x.Item1, StringComparer.Ordinal)
            .ToList();

      #region private

      /// <summary>The game's own code: the mod layer, without the console's test commands and cr.testall.</summary>
      private static List<SourceFile> GameFiles(IReadOnlyList<SourceFile> files)
         => files.Where(f => f.Layer == Layer.Mod
                             && !("/" + f.RelativePath).Contains("/Diagnostics/")
                             && !System.IO.Path.GetFileName(f.RelativePath).StartsWith("ModCheats", StringComparison.Ordinal))
                 .ToList();

      private static string SiteOf(MemberAccessExpressionSyntax m)
      {
         string type = m.Ancestors().OfType<TypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";
         string member = m.Ancestors().OfType<MethodDeclarationSyntax>().FirstOrDefault()?.Identifier.Text
                         ?? m.Ancestors().OfType<PropertyDeclarationSyntax>().FirstOrDefault()?.Identifier.Text
                         ?? "(field)";

         return $"{type}.{member}";
      }

      #endregion
   }
}

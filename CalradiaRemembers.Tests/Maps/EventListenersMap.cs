// docs/maps/event-listeners.md: every campaign event the mod listens to, who listens, and which of the event's own
// reasons the listener's file names.
//
// The rescue ledger listened to HeroPrisonerReleased and acted on ONE of the engine's seven EndCaptivityDetail values,
// ReleasedAfterBattle, which is the engine freeing a prisoner by itself. The common case, the player choosing to let a
// beaten captor's prisoner go, is ReleasedByChoice and was dropped whole: Lordfadooboo rescued Lady Mesui and she met
// him afterwards as a stranger (20/09/2026). Nothing about that was visible without opening the file and knowing the
// enum. Here it reads "filters on EndCaptivityDetail: ReleasedAfterBattle", and the question "only that one?" asks
// itself.

#region

using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class EventListenersMap
   {
      public const string Path = "docs/maps/event-listeners.md";

      private const string Subscribe = "AddNonSerializedListener";

      /// <summary>A parameter type that reads like "which way did this happen" is the kind a listener filters on, and the kind it filters on too narrowly.</summary>
      private static readonly Regex ReasonLike = new(@"(Detail|Details|Reason|Kind|State|Result|Type)$", RegexOptions.Compiled);

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<Listener> listeners = ListenersOf(files);
         var sb = new StringBuilder();

         sb.AppendLine("# Event listeners: what the mod hears from the engine");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine($"{listeners.Count} subscriptions to {listeners.Select(l => l.Event).Distinct().Count()} campaign events, in {listeners.Select(l => l.Owner).Distinct().Count()} types.");
         sb.AppendLine("`Names` lists the values of a reason-like parameter (a Detail, a Reason, a Kind) that the listener's file");
         sb.AppendLine("mentions: an event with seven ways to happen and a listener that names one of them is a question worth asking.");
         sb.AppendLine();

         sb.AppendLine("## By event");
         sb.AppendLine();
         sb.AppendLine("| Event | Listener | Names |");
         sb.AppendLine("|---|---|---|");

         foreach (Listener listener in listeners.OrderBy(l => l.Event, StringComparer.Ordinal)
                                                .ThenBy(l => l.Owner, StringComparer.Ordinal)
                                                .ThenBy(l => l.Handler, StringComparer.Ordinal))
            sb.AppendLine($"| `{listener.Event}` | `{listener.Owner}.{listener.Handler}` | {DocText.Cell(listener.Names)} |");

         sb.AppendLine();
         sb.AppendLine("## By listener");
         sb.AppendLine();

         foreach (IGrouping<string, Listener> owner in listeners.GroupBy(l => l.Owner).OrderBy(g => g.Key, StringComparer.Ordinal))
            sb.AppendLine($"- `{owner.Key}`: {string.Join(", ", owner.Select(l => l.Event).Distinct().OrderBy(e => e, StringComparer.Ordinal))}");

         sb.AppendLine();

         return sb.ToString();
      }

      #region private

      private sealed record Listener(string Event, string Owner, string Handler, string Names);

      private static List<Listener> ListenersOf(IReadOnlyList<SourceFile> files)
      {
         var found = new List<Listener>();

         foreach (SourceFile file in files)
            foreach (InvocationExpressionSyntax call in file.Root.DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
               if (call.Expression is not MemberAccessExpressionSyntax {Name.Identifier.Text: Subscribe} subscribe) continue;
               if (subscribe.Expression is not MemberAccessExpressionSyntax source) continue;

               string owner = call.Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";
               ExpressionSyntax? handlerArg = call.ArgumentList.Arguments.Count > 1 ? call.ArgumentList.Arguments[1].Expression : null;
               string handler = handlerArg is IdentifierNameSyntax name ? name.Identifier.Text : "(inline)";

               found.Add(new Listener(source.Name.Identifier.Text, owner, handler, NamesFilteredOn(file, handler)));
            }

         return found;
      }

      /// <summary>For each reason-like parameter of the handler, the members of that type the file mentions anywhere.</summary>
      private static string NamesFilteredOn(SourceFile file, string handler)
      {
         MethodDeclarationSyntax? method = file.Root.DescendantNodes().OfType<MethodDeclarationSyntax>()
                                               .FirstOrDefault(m => m.Identifier.Text == handler);
         if (method == null) return "";

         var parts = new List<string>();

         foreach (string type in method.ParameterList.Parameters
                                       .Select(p => p.Type?.ToString().Split('.').Last() ?? "")
                                       .Where(t => ReasonLike.IsMatch(t))
                                       .Distinct())
         {
            List<string> members = file.Root.DescendantNodes().OfType<MemberAccessExpressionSyntax>()
                                       .Where(a => a.Expression.ToString().Split('.').Last() == type)
                                       .Select(a => a.Name.Identifier.Text)
                                       .Distinct()
                                       .OrderBy(m => m, StringComparer.Ordinal)
                                       .ToList();

            parts.Add(members.Count == 0 ? $"{type}: (none named, takes them all)" : $"{type}: {string.Join(", ", members)}");
         }

         return string.Join("; ", parts);
      }

      #endregion
   }
}

// Code written by Gabriel Mailhot, 21/09/2026.
// docs/maps/inventory.md: every type in the system, by layer and namespace, with the one sentence that says what it
// is. This is the GENERIC net. A specialised map only watches the dimension it was built for; a new mechanism nobody
// planned a map for still adds a type, renames one or moves one, and shows up here.

#region

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class InventoryMap
   {
      public const string Path = "docs/maps/inventory.md";

      /// <summary>Only files at least this long are listed as large, and sizes are rounded DOWN to this step, so the list moves when a file changes class, not on every commit.</summary>
      private const int LargeFileStep = 500;

      private const int LargeFileFloor = 1000;

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<TypeEntry> types = TypesOf(files);
         var sb = new StringBuilder();

         sb.AppendLine("# Inventory: every type, by layer and namespace");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("Read it to answer \"does this concept already exist, and where does it live\" BEFORE adding a type. The");
         sb.AppendLine("sentence beside each type is the first sentence of its own doc comment; `" + DocText.NoSummary + "` is a gap worth closing.");
         sb.AppendLine();

         foreach (Layer layer in Enum.GetValues<Layer>())
         {
            List<TypeEntry> inLayer = types.Where(t => t.Layer == layer).ToList();
            sb.AppendLine($"- **{LayerName(layer)}**: {inLayer.Count} types in {inLayer.Select(t => t.Namespace).Distinct().Count()} namespaces, "
                        + $"{inLayer.Count(t => t.Summary == DocText.NoSummary)} without a summary");
         }

         sb.AppendLine();
         AppendLargeFiles(sb, files);

         foreach (Layer layer in Enum.GetValues<Layer>())
         {
            sb.AppendLine($"## {LayerName(layer)}");
            sb.AppendLine();

            foreach (IGrouping<string, TypeEntry> ns in types.Where(t => t.Layer == layer)
                                                             .GroupBy(t => t.Namespace)
                                                             .OrderBy(g => g.Key, StringComparer.Ordinal))
            {
               sb.AppendLine($"### {ns.Key} ({ns.Count()})");
               sb.AppendLine();
               sb.AppendLine("| Type | Kind | What it is |");
               sb.AppendLine("|---|---|---|");

               foreach (TypeEntry type in ns.OrderBy(t => t.Name, StringComparer.Ordinal))
                  sb.AppendLine($"| `{type.Name}` | {type.Kind} | {DocText.Cell(type.Summary)} |");

               sb.AppendLine();
            }
         }

         return sb.ToString();
      }

      public static string LayerName(Layer layer) => layer switch {
         Layer.Mod => "Mod (engine-bound, `CalradiaRemembers`)",
         Layer.Logic => "Logic (pure, `CalradiaRemembers.Logic`)",
         _ => "SDK (engine-agnostic, `NpcMemoryService.Core`)"
      };

      #region private

      private sealed record TypeEntry(Layer Layer, string Namespace, string Name, string Kind, string Summary);

      /// <summary>Top-level types only. A partial type spread over several files is one entry, described by whichever part carries the summary.</summary>
      private static List<TypeEntry> TypesOf(IReadOnlyList<SourceFile> files)
      {
         var found = new Dictionary<(Layer, string, string), TypeEntry>();
         var parts = new Dictionary<(Layer, string, string), int>();

         foreach (SourceFile file in files)
            foreach (MemberDeclarationSyntax member in file.Root.DescendantNodes().OfType<MemberDeclarationSyntax>())
            {
               if (member is not (BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)) continue;
               if (member.Parent is not (BaseNamespaceDeclarationSyntax or CompilationUnitSyntax)) continue;

               string name = member switch {
                  BaseTypeDeclarationSyntax type => type.Identifier.Text,
                  DelegateDeclarationSyntax del => del.Identifier.Text,
                  _ => ""
               };
               string ns = (member.Parent as BaseNamespaceDeclarationSyntax)?.Name.ToString() ?? "(global)";
               var key = (file.Layer, ns, name);

               parts[key] = parts.TryGetValue(key, out int n) ? n + 1 : 1;

               var entry = new TypeEntry(file.Layer, ns, name, KindOf(member), DocText.FirstSentenceOf(member));
               if (!found.TryGetValue(key, out TypeEntry? existing) || existing.Summary == DocText.NoSummary)
                  found[key] = entry;
            }

         return found.Select(kv => parts[kv.Key] > 1 ? kv.Value with {Kind = $"{kv.Value.Kind}, partial over {parts[kv.Key]} files"} : kv.Value)
                     .ToList();
      }

      private static string KindOf(MemberDeclarationSyntax member)
      {
         IEnumerable<string> modifiers = member.Modifiers
                                               .Where(m => m.IsKind(SyntaxKind.PublicKeyword) || m.IsKind(SyntaxKind.InternalKeyword)
                                                        || m.IsKind(SyntaxKind.StaticKeyword) || m.IsKind(SyntaxKind.AbstractKeyword))
                                               .Select(m => m.Text);

         string keyword = member switch {
            ClassDeclarationSyntax => "class",
            StructDeclarationSyntax => "struct",
            InterfaceDeclarationSyntax => "interface",
            EnumDeclarationSyntax => "enum",
            RecordDeclarationSyntax => "record",
            DelegateDeclarationSyntax => "delegate",
            _ => "type"
         };

         return string.Join(" ", modifiers.Append(keyword));
      }

      private static void AppendLargeFiles(StringBuilder sb, IReadOnlyList<SourceFile> files)
      {
         List<SourceFile> large = files.Where(f => f.LineCount >= LargeFileFloor)
                                       .OrderByDescending(f => f.LineCount / LargeFileStep)
                                       .ThenBy(f => f.RelativePath, StringComparer.Ordinal)
                                       .ToList();

         sb.AppendLine($"## Files of {LargeFileFloor} lines or more");
         sb.AppendLine();
         sb.AppendLine($"Rounded DOWN to {LargeFileStep} lines, so this list moves when a file changes class, not on every commit. A file");
         sb.AppendLine("this long is where the overall picture is hardest to hold, whatever else is true of it.");
         sb.AppendLine();
         sb.AppendLine("| Lines | Layer | File |");
         sb.AppendLine("|---|---|---|");

         foreach (SourceFile file in large)
            sb.AppendLine($"| {file.LineCount / LargeFileStep * LargeFileStep}+ | {file.Layer} | `{file.RelativePath}` |");

         sb.AppendLine();
      }

      #endregion
   }
}

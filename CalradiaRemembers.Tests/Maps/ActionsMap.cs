// Code written by Gabriel Mailhot, 30/09/2026.
// docs/maps/actions.md: every path where a character acts or is placed before the player, and where it asks the
// one gate (NpcActionGate: alive, in the world, of age, free, not the player).
//
// Gabriel, 30/09/2026, after a baby son asked to discuss warfare: every NPC action should pass common conditions, and
// fail to happen when they are not met. An inventory that day found about a dozen paths with a dozen filters, two of
// them checking age. The gate is the rule; this map is how its reach is SEEN: each kind, each place that asks for it,
// and every place that writes a letter straight into the post, with whether it asks. RatchetTests holds the two walls.

#region

using System.Text;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class ActionsMap
   {
      public const string Path = "docs/maps/actions.md";

      private const string Gate = "ActionGate";

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<SourceFile> mod = GameFiles(files);
         var sb = new StringBuilder();

         sb.AppendLine("# Actions: where a character acts or is placed before the player, and the gate each one asks");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("Every initiative, and every action a character takes when the player summons them (a council seat), asks");
         sb.AppendLine("`ActionGate` (the live side of `NpcActionGate`): the character is alive, in the world (not disabled),");
         sb.AppendLine("of age (`Hero.IsChild`, never a rank: `IsLord` is an occupation; a council seat takes the council's own age,");
         sb.AppendLine("13), free, and not the player. Each path keeps its own conditions on top. Answering the player (a reply), being");
         sb.AppendLine("the subject of news, and the verbs a model emits in conversation have their own rules.");
         sb.AppendLine();
         sb.AppendLine("## By kind");
         sb.AppendLine();
         sb.AppendLine("| Kind | Asked in |");
         sb.AppendLine("|---|---|");
         foreach (IGrouping<string, (string Kind, string Site)> kind in KindSites(mod).GroupBy(k => k.Kind).OrderBy(g => g.Key, StringComparer.Ordinal))
            sb.AppendLine($"| `{kind.Key}` | {string.Join(", ", kind.Select(k => $"`{k.Site}`").Distinct().OrderBy(x => x, StringComparer.Ordinal))} |");

         sb.AppendLine();
         sb.AppendLine("## Letters written straight into the post");
         sb.AppendLine();
         sb.AppendLine("A letter added to a character's `SentLetters` outside the letter pipeline is an initiative the pipeline's own");
         sb.AppendLine("gate never saw; the file must ask the gate itself.");
         sb.AppendLine();
         sb.AppendLine("| File | Asks the gate |");
         sb.AppendLine("|---|---|");
         foreach ((string file, bool asks) in DirectLetterFiles(files))
            sb.AppendLine($"| `{file}` | {(asks ? "yes" : "**NO**")} |");

         sb.AppendLine();
         sb.AppendLine("## `IsAlive` read on its own");
         sb.AppendLine();
         sb.AppendLine("The engine's `Hero.IsAlive` means only \"not dead\": a hero the game has taken out of the world (disabled)");
         sb.AppendLine("reads alive, and `Clan.Heroes` keeps both the dead and the disabled. A check that means \"may act\" asks");
         sb.AppendLine("`ActionGate`; one that means \"is in the world\" asks `HeroPresence.IsInTheWorld`. What is left below is");
         sb.AppendLine("the backlog (a baseline in `RatchetTests` that may only go down); many are bookkeeping (\"is the subject of");
         sb.AppendLine("this memory still alive\") where death alone is the question.");
         sb.AppendLine();
         List<(string File, int Count)> bare = BareIsAliveReads(files);
         sb.AppendLine($"{bare.Sum(b => b.Count)} reads in {bare.Count} files.");
         sb.AppendLine();
         sb.AppendLine("| File | Reads |");
         sb.AppendLine("|---|---|");
         foreach ((string file, int count) in bare)
            sb.AppendLine($"| `{file}` | {count} |");

         sb.AppendLine();

         return sb.ToString();
      }

      /// <summary>Each ActionKind the game code names, with the Type.Method naming it.</summary>
      public static List<(string Kind, string Site)> KindSites(IReadOnlyList<SourceFile> files)
         => GameFiles(files)
            .SelectMany(f => f.Root.DescendantNodes().OfType<MemberAccessExpressionSyntax>()
                              .Where(m => m.Expression.ToString().EndsWith("ActionKind", StringComparison.Ordinal))
                              .Select(m => (m.Name.Identifier.Text, SiteOf(m))))
            .ToList();

      /// <summary>Every game file that adds a letter to SentLetters directly, and whether it asks the gate.</summary>
      public static List<(string File, bool AsksGate)> DirectLetterFiles(IReadOnlyList<SourceFile> files)
         => GameFiles(files)
            .Where(f => f.Root.DescendantNodes().OfType<InvocationExpressionSyntax>()
                         .Any(i => i.Expression is MemberAccessExpressionSyntax {Name.Identifier.Text: "Add"} m
                                   && m.Expression.ToString().EndsWith("SentLetters", StringComparison.Ordinal)))
            .Select(f => (f.RelativePath, f.Text.Contains(Gate + ".Allows") || f.Text.Contains(Gate + ".Check")))
            .OrderBy(x => x.Item1, StringComparer.Ordinal)
            .ToList();

      /// <summary>
      ///   Game files that read <c>IsAlive</c> themselves instead of asking ActionGate or HeroPresence, with how many
      ///   times. The two doors themselves are left out: they are where the read belongs.
      /// </summary>
      public static List<(string File, int Count)> BareIsAliveReads(IReadOnlyList<SourceFile> files)
         => GameFiles(files)
            .Where(f => !f.RelativePath.EndsWith("Mapping/ActionGate.cs", StringComparison.Ordinal)
                        && !f.RelativePath.EndsWith("Mapping/HeroPresence.cs", StringComparison.Ordinal))
            .Select(f => (f.RelativePath, f.Root.DescendantNodes().OfType<IdentifierNameSyntax>().Count(n => n.Identifier.Text == "IsAlive")))
            .Where(x => x.Item2 > 0)
            .OrderBy(x => x.Item1, StringComparer.Ordinal)
            .ToList();

      #region private

      /// <summary>The game's own code: the mod layer, without the console's test commands and cr.test all.</summary>
      private static List<SourceFile> GameFiles(IReadOnlyList<SourceFile> files)
         => files.Where(f => f.Layer == Layer.Mod
                             && !("/" + f.RelativePath).Contains("/Diagnostics/")
                             && !System.IO.Path.GetFileName(f.RelativePath).StartsWith("ModCheats", StringComparison.Ordinal))
                 .ToList();

      private static string SiteOf(MemberAccessExpressionSyntax m)
      {
         string type = m.Ancestors().OfType<TypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";
         string member = m.Ancestors().OfType<MethodDeclarationSyntax>().FirstOrDefault()?.Identifier.Text
                         ?? m.Ancestors().OfType<PropertyDeclarationSyntax>().FirstOrDefault()?.Identifier.Text
                         ?? "(field)";

         return $"{type}.{member}";
      }

      #endregion
   }
}

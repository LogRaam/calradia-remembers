// Code written by Gabriel Mailhot, 21/09/2026.
// docs/maps/verbs.md: every action a character can emit, and every place it has to be written down for it to work.
//
// An action is declared in up to seven places: the SDK catalogue the interpreter is taught from, the bridge's handled
// list, the bridge's dispatch switch, a verb class, the verb registry, the set of actions taught on a turn, and the
// bench that measures whether a model emits it. Adding hear_account (19/09/2026) meant touching all seven, and the
// first SDK run failed on the one that had been missed. `cr.testall action_catalog_parity` guards two of those seven
// against each other, in the game; this shows all seven, here. A row with a hole in it is either a bridge-native action
// that needs no verb class, which is fine, or a verb that is taught and cannot run, which is a bug a player finds.

#region

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class VerbsMap
   {
      public const string Path = "docs/maps/verbs.md";

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         HashSet<string> catalogue = SpecNames(File(files, Layer.Sdk, "Actions/GameActionCatalog.cs"));
         SourceFile? bridge = File(files, Layer.Mod, "GameState/BannerlordGameStateBridge.cs");
         HashSet<string> handled = LiteralsInField(bridge, "HandledActionTypes");
         HashSet<string> dispatched = CaseLabels(bridge);
         HashSet<string> taught = AllLiterals(File(files, Layer.Logic, "Actions/TaughtActionSet.cs"));
         Dictionary<string, string> verbClasses = VerbClasses(files);
         HashSet<string> registered = RegisteredClasses(File(files, Layer.Mod, "Verbs/VerbRegistry.cs"));
         Dictionary<string, int> bench = BenchCases(File(files, Layer.Sdk, "Actions/ActionBenchCatalog.cs"));

         // A `case` label never ADDS a row: the bridge switches on other strings too (a wound's severity, for one),
         // and those are not actions. It only answers "is this action dispatched" for a name known from elsewhere.
         List<string> names = catalogue.Union(handled).Union(verbClasses.Keys)
                                       .OrderBy(n => n, StringComparer.Ordinal).ToList();

         var sb = new StringBuilder();
         sb.AppendLine("# Verbs: every action, and every place it has to be declared");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine($"{names.Count} actions. `Catalogue` is the SDK's `GameActionCatalog` (what the interpreter is taught); `Handled` and");
         sb.AppendLine("`Case` are the bridge's list and its dispatch switch; `Verb class` implements `IConversationVerb` and `Registered`");
         sb.AppendLine("is `VerbRegistry`; `Taught` is `TaughtActionSet`; `Bench` counts the phrasings the action bench holds for it.");
         sb.AppendLine("A hole is not always a bug (a bridge-native action has no verb class), but every hole should be one on purpose.");
         sb.AppendLine();
         sb.AppendLine("| Action | Catalogue | Handled | Case | Verb class | Registered | Taught | Bench |");
         sb.AppendLine("|---|---|---|---|---|---|---|---|");

         foreach (string name in names)
         {
            verbClasses.TryGetValue(name, out string? verbClass);
            sb.AppendLine($"| `{name}` | {Mark(catalogue.Contains(name))} | {Mark(handled.Contains(name))} | {Mark(dispatched.Contains(name))} | "
                        + $"{(verbClass == null ? "" : $"`{verbClass}`")} | {Mark(verbClass != null && registered.Contains(verbClass))} | "
                        + $"{Mark(taught.Contains(name))} | {(bench.TryGetValue(name, out int n) ? n.ToString() : "")} |");
         }

         sb.AppendLine();

         return sb.ToString();
      }

      #region private

      private static string Mark(bool present) => present ? "yes" : "";

      internal static SourceFile? File(IReadOnlyList<SourceFile> files, Layer layer, string relativePath)
         => files.FirstOrDefault(f => f.Layer == layer && f.RelativePath == relativePath);

      private static string? Literal(ExpressionSyntax? expression)
         => expression is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.StringLiteralExpression) ? literal.Token.ValueText : null;

      /// <summary>Spec("name", ...) in the catalogue: the first argument is the action's type.</summary>
      internal static HashSet<string> SpecNames(SourceFile? file)
         => (file?.Root.DescendantNodes().OfType<InvocationExpressionSyntax>() ?? Enumerable.Empty<InvocationExpressionSyntax>())
            .Where(c => c.Expression is IdentifierNameSyntax {Identifier.Text: "Spec"})
            .Select(c => Literal(c.ArgumentList.Arguments.FirstOrDefault()?.Expression))
            .Where(n => n != null)
            .Select(n => n!)
            .ToHashSet();

      internal static HashSet<string> LiteralsInField(SourceFile? file, string fieldName)
         => (file?.Root.DescendantNodes().OfType<VariableDeclaratorSyntax>() ?? Enumerable.Empty<VariableDeclaratorSyntax>())
            .Where(v => v.Identifier.Text == fieldName)
            .SelectMany(v => v.DescendantNodes().OfType<LiteralExpressionSyntax>())
            .Select(Literal)
            .Where(n => n != null)
            .Select(n => n!)
            .ToHashSet();

      internal static HashSet<string> CaseLabels(SourceFile? file)
         => (file?.Root.DescendantNodes().OfType<CaseSwitchLabelSyntax>() ?? Enumerable.Empty<CaseSwitchLabelSyntax>())
            .Select(l => Literal(l.Value))
            .Where(n => n != null)
            .Select(n => n!)
            .ToHashSet();

      private static HashSet<string> AllLiterals(SourceFile? file)
         => (file?.Root.DescendantNodes().OfType<LiteralExpressionSyntax>() ?? Enumerable.Empty<LiteralExpressionSyntax>())
            .Select(Literal)
            .Where(n => n != null)
            .Select(n => n!)
            .ToHashSet();

      /// <summary>action name -> the class that implements it, read from `public string Name => "x";`.</summary>
      internal static Dictionary<string, string> VerbClasses(IReadOnlyList<SourceFile> files)
      {
         var found = new Dictionary<string, string>();

         foreach (ClassDeclarationSyntax type in files.SelectMany(f => f.Root.DescendantNodes().OfType<ClassDeclarationSyntax>()))
         {
            if (type.BaseList?.Types.Any(t => t.Type.ToString() == "IConversationVerb") != true) continue;

            string? name = type.Members.OfType<PropertyDeclarationSyntax>()
                               .Where(p => p.Identifier.Text == "Name")
                               .Select(p => Literal(p.ExpressionBody?.Expression))
                               .FirstOrDefault(n => n != null);

            if (name != null) found[name] = type.Identifier.Text;
         }

         return found;
      }

      internal static HashSet<string> RegisteredClasses(SourceFile? file)
         => (file?.Root.DescendantNodes().OfType<InvocationExpressionSyntax>() ?? Enumerable.Empty<InvocationExpressionSyntax>())
            .Where(c => c.Expression is MemberAccessExpressionSyntax {Name.Identifier.Text: "Register"})
            .SelectMany(c => c.ArgumentList.Arguments.Select(a => a.Expression).OfType<ObjectCreationExpressionSyntax>())
            .Select(o => o.Type.ToString())
            .ToHashSet();

      /// <summary>ActionBenchCase.Expect("id", "type", ...): the second argument is the action the phrasing is for.</summary>
      private static Dictionary<string, int> BenchCases(SourceFile? file)
         => (file?.Root.DescendantNodes().OfType<InvocationExpressionSyntax>() ?? Enumerable.Empty<InvocationExpressionSyntax>())
            .Where(c => c.Expression is MemberAccessExpressionSyntax {Name.Identifier.Text: "Expect"} && c.ArgumentList.Arguments.Count > 1)
            .Select(c => Literal(c.ArgumentList.Arguments[1].Expression))
            .Where(n => n != null)
            .GroupBy(n => n!)
            .ToDictionary(g => g.Key, g => g.Count());

      #endregion
   }
}

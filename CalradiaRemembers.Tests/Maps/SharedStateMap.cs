// Code written by Gabriel Mailhot, 21/09/2026.
// docs/maps/shared-state.md: everything that outlives the call that wrote it. Static mutable fields, static settable
// properties, and the static collections whose contents change.
//
// Two reports this week were values captured once and read for ever after. {{faction}} was read from the player's
// realm when the prompt builder was constructed and kept until the next load, so a player expelled from a kingdom was
// still named as belonging to it (tashmetu, 19/09/2026). And who had sought whom in a conversation was consumed on
// the first read and then simply gone (Fakade, same day). A stale value and a vanished one are the same defect, a
// lifetime nobody decided, and they live in exactly the places this map lists. It cannot say WHICH of these is
// stale, only where the question has to be asked. That is the point of listing them.

#region

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class SharedStateMap
   {
      public const string Path = "docs/maps/shared-state.md";

      private static readonly string[] MutableCollections = {"Dictionary", "List", "HashSet", "SortedSet", "SortedDictionary", "Queue", "Stack", "Concurrent"};

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<Entry> entries = EntriesOf(files);
         var sb = new StringBuilder();

         sb.AppendLine("# Shared state: what outlives the call that wrote it");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine($"{entries.Count} static members that can change after start-up, in {entries.Select(e => e.Owner).Distinct().Count()} types. For each one the");
         sb.AppendLine("question is the same: who resets it, and when? Across a save and load, across two campaigns in one session,");
         sb.AppendLine("across two conversations. A NEW LINE here is a new lifetime to decide, not just a new field.");
         sb.AppendLine();

         foreach (Layer layer in Enum.GetValues<Layer>())
         {
            sb.AppendLine($"## {InventoryMap.LayerName(layer)}");
            sb.AppendLine();
            sb.AppendLine("| Owner | Member | Type | Kind |");
            sb.AppendLine("|---|---|---|---|");

            foreach (Entry entry in entries.Where(e => e.Layer == layer)
                                           .OrderBy(e => e.Owner, StringComparer.Ordinal)
                                           .ThenBy(e => e.Member, StringComparer.Ordinal))
               sb.AppendLine($"| `{entry.Owner}` | `{entry.Member}` | `{DocText.Cell(entry.Type)}` | {entry.Kind} |");

            sb.AppendLine();
         }

         return sb.ToString();
      }

      #region private

      private sealed record Entry(Layer Layer, string Owner, string Member, string Type, string Kind);

      /// <summary>A type through which the contents cannot be changed: IReadOnly*, IEnumerable, Immutable*.</summary>
      private static bool IsReadOnlyView(string type)
         => type.StartsWith("IReadOnly", StringComparison.Ordinal)
            || type.StartsWith("IEnumerable", StringComparison.Ordinal)
            || type.StartsWith("Immutable", StringComparison.Ordinal);

      private static List<Entry> EntriesOf(IReadOnlyList<SourceFile> files)
      {
         var found = new List<Entry>();

         foreach (SourceFile file in files)
         {
            foreach (FieldDeclarationSyntax field in file.Root.DescendantNodes().OfType<FieldDeclarationSyntax>())
            {
               if (!field.Modifiers.Any(m => m.IsKind(SyntaxKind.StaticKeyword))) continue;
               if (field.Modifiers.Any(m => m.IsKind(SyntaxKind.ConstKeyword))) continue;

               string type = field.Declaration.Type.ToString();
               bool isReadonly = field.Modifiers.Any(m => m.IsKind(SyntaxKind.ReadOnlyKeyword));

               // A readonly reference to a collection is still a place where contents change.
               if (isReadonly && !MutableCollections.Any(c => type.Contains(c, StringComparison.Ordinal))) continue;

               // ...unless it is held through a read-only view. "IReadOnlyDictionary" contains "Dictionary", so until
               // 27/09/2026 six read-only tables were listed here as contents that change: a line that was wrong without
               // anyone noticing, found when a new lookup table was typed read-only and stayed on the map.
               if (isReadonly && IsReadOnlyView(type)) continue;

               foreach (VariableDeclaratorSyntax variable in field.Declaration.Variables)
                  found.Add(new Entry(file.Layer, OwnerOf(field), variable.Identifier.Text, type, isReadonly ? "collection, contents change" : "field"));
            }

            foreach (PropertyDeclarationSyntax property in file.Root.DescendantNodes().OfType<PropertyDeclarationSyntax>())
            {
               if (!property.Modifiers.Any(m => m.IsKind(SyntaxKind.StaticKeyword))) continue;

               bool settable = property.AccessorList?.Accessors.Any(a => a.IsKind(SyntaxKind.SetAccessorDeclaration)) == true;
               if (!settable) continue;

               found.Add(new Entry(file.Layer, OwnerOf(property), property.Identifier.Text, property.Type.ToString(), "settable property"));
            }
         }

         return found;
      }

      private static string OwnerOf(MemberDeclarationSyntax member)
         => member.Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";

      #endregion
   }
}

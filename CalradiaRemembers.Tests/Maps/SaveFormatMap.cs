// Code written by Gabriel Mailhot, 21/09/2026.
// docs/maps/save-format.md: every key the mod writes into a save, and every saveable type id it claims.
//
// This one is a CONTRACT, not a view. The others show the shape of the code; this shows a promise made to every
// player with a campaign in progress. Gabriel's hard rule (feedback, 2026-07): additive SyncData keys only, idempotent
// backfill, graceful degradation. A key renamed is a player's grudges, letters or marriage silently gone on their
// next load, and nothing fails: the old key is simply never read again. Type ids are worse, since the engine
// reconciles saves by the raw number (the EOE collision, `b3c6514`: two mods claiming 300000001 crashed the boot).
//
// So a key that DISAPPEARS is not something a regeneration may quietly absorb. MapsAreCurrentTests refuses it outright,
// update mode included, until the removal is declared on purpose (see SaveKeysMayNotDisappear there).

#region

using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class SaveFormatMap
   {
      public const string Path = "docs/maps/save-format.md";

      private static readonly string[] DefinitionCalls = {"AddClassDefinition", "AddStructDefinition", "AddEnumDefinition", "AddInterfaceDefinition", "ConstructContainerDefinition"};

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<SourceFile> mod = files.Where(f => f.Layer == Layer.Mod).ToList();
         List<SaveKey> keys = KeysOf(mod);
         var sb = new StringBuilder();

         sb.AppendLine("# Save format: what the mod writes into a player's campaign");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("**This is a contract with every campaign in progress.** Keys are ADDITIVE ONLY: a renamed or removed key is a");
         sb.AppendLine("player's data silently gone on their next load, and nothing fails when it happens. A key that disappears from");
         sb.AppendLine("this file is refused by the suite, regeneration included, until it is declared on purpose.");
         sb.AppendLine();
         sb.AppendLine($"## Keys ({keys.Count})");
         sb.AppendLine();
         sb.AppendLine("| Key | Written by | Declared as |");
         sb.AppendLine("|---|---|---|");

         foreach (SaveKey key in keys.OrderBy(k => k.Value, StringComparer.Ordinal).ThenBy(k => k.Owner, StringComparer.Ordinal))
            sb.AppendLine($"| `{key.Value}` | `{key.Owner}` | {key.DeclaredAs} |");

         sb.AppendLine();
         AppendTypeIds(sb, mod);

         return sb.ToString();
      }

      /// <summary>The keys a committed or a freshly generated map lists, for the may-not-disappear guard.</summary>
      public static HashSet<string> KeysListedIn(string mapText)
      {
         string keysSection = Regex.Split(mapText.Replace("\r\n", "\n"), @"^## ", RegexOptions.Multiline)
                                   .FirstOrDefault(s => s.StartsWith("Keys", StringComparison.Ordinal)) ?? "";

         return Regex.Matches(keysSection, @"^\| `([^`]+)` \|", RegexOptions.Multiline).Select(m => m.Groups[1].Value).ToHashSet();
      }

      #region private

      private sealed record SaveKey(string Value, string Owner, string DeclaredAs);

      /// <summary>
      ///   A save key is a string that reaches SyncData. Three ways it gets there: written as a literal at the call, held
      ///   in a constant the call names, or held in a constant named *SaveKey* and handed to a helper that makes the call.
      /// </summary>
      private static List<SaveKey> KeysOf(List<SourceFile> files)
      {
         var found = new Dictionary<(string, string), SaveKey>();

         foreach (SourceFile file in files)
         {
            Dictionary<string, string> constants = file.Root.DescendantNodes().OfType<FieldDeclarationSyntax>()
                                                       .Where(f => f.Declaration.Type.ToString() == "string")
                                                       .SelectMany(f => f.Declaration.Variables)
                                                       .Where(v => StringOf(v.Initializer?.Value) != null)
                                                       .GroupBy(v => v.Identifier.Text)
                                                       .ToDictionary(g => g.Key, g => StringOf(g.First().Initializer!.Value)!);

            // TWO DETECTION MODES, AND EACH LINE SAYS WHICH (Gabriel, 26/09/2026: "toute carte qui melange deux modes de
            // detection devrait dire, pour chaque ligne, lequel l'a produite"). The SyncData call is the FACT; a constant
            // named *SaveKey* is found by its NAME, for a key handed to a helper that makes the call. A key both find is
            // labelled by the fact, which is read first so it wins; before 26/09/2026 the name pass ran first and a key the
            // call itself confirmed read as though only its name had.
            foreach (InvocationExpressionSyntax call in file.Root.DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
               if (call.Expression is not MemberAccessExpressionSyntax {Name.Identifier.Text: "SyncData"}) continue;

               ExpressionSyntax? first = call.ArgumentList.Arguments.FirstOrDefault()?.Expression;
               string owner = call.Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";

               if (StringOf(first) is { } literal)
                  Add(found, literal, owner, "literal at the SyncData call (fact)");
               else if (first is IdentifierNameSyntax id && constants.TryGetValue(id.Identifier.Text, out string? value))
                  Add(found, value, owner, $"constant `{id.Identifier.Text}` passed to SyncData (fact)");
            }

            foreach ((string name, string value) in constants.Where(c => c.Key.Contains("SaveKey", StringComparison.Ordinal)))
               Add(found, value, OwnerOfField(file, name), $"constant `{name}`, found by its name (name)");
         }

         return found.Values.ToList();
      }

      private static void Add(Dictionary<(string, string), SaveKey> found, string value, string owner, string declaredAs)
      {
         if (!found.ContainsKey((value, owner))) found[(value, owner)] = new SaveKey(value, owner, declaredAs);
      }

      private static string? StringOf(ExpressionSyntax? expression)
         => expression is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.StringLiteralExpression) ? literal.Token.ValueText : null;

      private static string OwnerOfField(SourceFile file, string fieldName)
         => file.Root.DescendantNodes().OfType<VariableDeclaratorSyntax>()
                .FirstOrDefault(v => v.Identifier.Text == fieldName)?
                .Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";

      private static void AppendTypeIds(StringBuilder sb, List<SourceFile> files)
      {
         sb.AppendLine("## Saveable type ids");
         sb.AppendLine();
         sb.AppendLine("The engine reconciles a save by the raw NUMBER, not the type name, so a changed id orphans old saves and a");
         sb.AppendLine("reused one crashes the boot when another mod holds it.");
         sb.AppendLine();
         sb.AppendLine("| Definition | In |");
         sb.AppendLine("|---|---|");

         foreach ((string text, string owner) in files.SelectMany(f => f.Root.DescendantNodes().OfType<InvocationExpressionSyntax>()
                                                                        .Where(c => c.Expression is IdentifierNameSyntax id && DefinitionCalls.Contains(id.Identifier.Text))
                                                                        .Select(c => (Regex.Replace(c.ToString(), @"\s+", " "),
                                                                                      c.Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)")))
                                                      .OrderBy(x => x.Item2, StringComparer.Ordinal).ThenBy(x => x.Item1, StringComparer.Ordinal))
            sb.AppendLine($"| `{DocText.Cell(text)}` | `{owner}` |");

         sb.AppendLine();
         sb.AppendLine("## Saveable members");
         sb.AppendLine();
         sb.AppendLine("| Member | Id |");
         sb.AppendLine("|---|---|");

         foreach ((string member, string id) in files.SelectMany(f => f.Root.DescendantNodes().OfType<AttributeSyntax>()
                                                                       .Where(a => a.Name.ToString() is "SaveableField" or "SaveableProperty")
                                                                       .Select(a => (MemberOf(a), a.ArgumentList?.Arguments.FirstOrDefault()?.ToString() ?? "?")))
                                                     .OrderBy(x => x.Item1, StringComparer.Ordinal))
            sb.AppendLine($"| `{member}` | {id} |");

         sb.AppendLine();
      }

      private static string MemberOf(AttributeSyntax attribute)
      {
         MemberDeclarationSyntax? member = attribute.Ancestors().OfType<MemberDeclarationSyntax>().FirstOrDefault();
         string owner = member?.Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";

         string name = member switch {
            FieldDeclarationSyntax field => field.Declaration.Variables.First().Identifier.Text,
            PropertyDeclarationSyntax property => property.Identifier.Text,
            _ => "?"
         };

         return $"{owner}.{name}";
      }

      #endregion
   }
}

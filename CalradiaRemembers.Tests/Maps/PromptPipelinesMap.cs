// docs/maps/prompt-pipelines.md: every place the model is called, what writes its prompt, and which editable file in
// ModuleData reaches which of them. Shipped to players beside PROMPT_SECTIONS.md as Docs/PROMPT_PIPELINES.md.
//
// prompt-sections.md maps ONE prompt, the character's, section by section; nothing said that there are a dozen others
// (letters, envoys, the council, memory summaries, strategic reports) or where a player's own text goes. Icezera
// (Discord, 12/11/2026) asked where to put instructions of their own; the answer, post_history_instructions.txt, reaches
// conversations and strategic reports but not the council, and only reading three files told it. CatWithFourEyes (same
// day): "can we have something like manual with prompt pipelines for different things?" Gabriel: "go pour la map".
//
// Read from FACTS, not names: a pipeline is a method that calls ILlmClient.CompleteAsync, the one door to the model; a
// file is a NarrativeLoader.ReadFile call; a reader is a member access through NarrativeLoader. Two parts are matched
// by NAME and say so: the callers of the conversation path (ChatAsync and its kin) and the Build* calls a pipeline makes.

#region

using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class PromptPipelinesMap
   {
      public const string Path = "docs/maps/prompt-pipelines.md";

      /// <summary>The one door to the model (ILlmClient).</summary>
      private const string ModelCall = "CompleteAsync";

      /// <summary>The service whose methods are the character conversation path every 1:1 scene and letter goes through.</summary>
      private const string ConversationService = "NpcChatService";

      private const string Loader = "NarrativeLoader";

      private const string LoaderRead = "ReadFile";

      /// <summary>The type a prompt profile is applied through; whoever references it is reached by a profile.</summary>
      private const string ProfileLayout = "PromptLayout";

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         var sb = new StringBuilder();
         sb.AppendLine("# Prompt pipelines: where the model is called, and where your text goes");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`. Shipped as `Docs/PROMPT_PIPELINES.md`.");
         sb.AppendLine();
         sb.AppendLine("**Blind spots.** A pipeline is a method that calls `ILlmClient.CompleteAsync` (fact). `Prompt from` lists the");
         sb.AppendLine("`*PromptBuilder` types the method names and the `Build*` methods it calls, by name. The conversation path's callers");
         sb.AppendLine("are found by method name, so a method elsewhere with the same name would be listed too. A file read by a loader");
         sb.AppendLine("other than `NarrativeLoader` (tales, scenarios, styles, prompt profiles) is not in the files table.");
         sb.AppendLine();

         List<Pipeline> pipelines = PipelinesOf(files);
         sb.AppendLine("## Where the model is called");
         sb.AppendLine();
         sb.AppendLine($"{pipelines.Count} methods call the model. `tool` marks a developer command or bench (`Diagnostics`, `ModCheats`, a `*Bench*` file), never run in play.");
         sb.AppendLine();
         sb.AppendLine("| Pipeline | Layer | Use | Prompt from | What it is |");
         sb.AppendLine("|---|---|---|---|---|");
         foreach (Pipeline p in pipelines.OrderBy(p => p.IsTool).ThenBy(p => p.Name, StringComparer.Ordinal))
            sb.AppendLine($"| `{p.Name}` | {p.Layer} | {(p.IsTool ? "tool" : "play")} | {DocText.Cell(p.PromptFrom)} | {DocText.Cell(p.Summary)} |");
         sb.AppendLine();

         AppendConversationPath(sb, files, pipelines);
         AppendFiles(sb, files);
         AppendProfiles(sb, files);

         return sb.ToString();
      }

      #region private

      private sealed record Pipeline(string Name, string Method, string Layer, bool IsTool, string PromptFrom, string Summary);

      private static string OwnerOf(SyntaxNode node) => node.AncestorsAndSelf().OfType<BaseTypeDeclarationSyntax>().LastOrDefault()?.Identifier.Text ?? "(none)";

      private static string MethodNameOf(SyntaxNode node)
         => node.AncestorsAndSelf().OfType<MethodDeclarationSyntax>().FirstOrDefault()?.Identifier.Text
            ?? node.AncestorsAndSelf().OfType<ConstructorDeclarationSyntax>().FirstOrDefault()?.Identifier.Text
            ?? node.AncestorsAndSelf().OfType<PropertyDeclarationSyntax>().FirstOrDefault()?.Identifier.Text
            ?? "(field)";

      private static string? CalledName(InvocationExpressionSyntax call)
         => call.Expression switch {
            MemberAccessExpressionSyntax m => m.Name.Identifier.Text,
            IdentifierNameSyntax i => i.Identifier.Text,
            GenericNameSyntax g => g.Identifier.Text,
            _ => null
         };

      private static bool IsToolFile(SourceFile f)
         => f.RelativePath.StartsWith("Diagnostics/", StringComparison.Ordinal) || f.RelativePath.Contains("/Diagnostics/")
            || System.IO.Path.GetFileName(f.RelativePath).StartsWith("ModCheats", StringComparison.Ordinal)
            || System.IO.Path.GetFileName(f.RelativePath).Contains("Bench");

      private static List<Pipeline> PipelinesOf(IReadOnlyList<SourceFile> files)
      {
         HashSet<string> builders = files.SelectMany(f => f.Root.DescendantNodes().OfType<ClassDeclarationSyntax>())
                                         .Select(c => c.Identifier.Text)
                                         .Where(n => n.EndsWith("PromptBuilder", StringComparison.Ordinal))
                                         .ToHashSet(StringComparer.Ordinal);
         var found = new Dictionary<string, Pipeline>(StringComparer.Ordinal);

         foreach (SourceFile file in files)
            foreach (InvocationExpressionSyntax call in file.Root.DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
               if (CalledName(call) != ModelCall || call.Expression is not MemberAccessExpressionSyntax) continue;

               // A client that wraps another (a fallback, a retry) forwards the call from its own CompleteAsync: not a pipeline.
               BaseMethodDeclarationSyntax? method = call.Ancestors().OfType<BaseMethodDeclarationSyntax>().FirstOrDefault();
               if (method is MethodDeclarationSyntax {Identifier.Text: ModelCall}) continue;

               string methodName = MethodNameOf(call);
               string name = $"{OwnerOf(call)}.{methodName}";
               if (found.ContainsKey(name)) continue;

               SyntaxNode body = (SyntaxNode?) method ?? call;
               IEnumerable<string> typesNamed = body.DescendantNodes().OfType<IdentifierNameSyntax>()
                                                    .Select(i => i.Identifier.Text)
                                                    .Where(builders.Contains);
               IEnumerable<string> buildCalls = body.DescendantNodes().OfType<InvocationExpressionSyntax>()
                                                    .Select(CalledName)
                                                    .Where(n => n != null && n.StartsWith("Build", StringComparison.Ordinal) && n.Length > 5)
                                                    .Select(n => n! + "()");
               List<string> from = typesNamed.Concat(buildCalls).Distinct().OrderBy(n => n, StringComparer.Ordinal).ToList();

               string summary = method != null ? DocText.FirstSentenceOf(method) : DocText.NoSummary;
               if (summary == DocText.NoSummary)
               {
                  BaseTypeDeclarationSyntax? type = call.Ancestors().OfType<BaseTypeDeclarationSyntax>().LastOrDefault();
                  if (type != null) summary = DocText.FirstSentenceOf(type);
               }

               found[name] = new Pipeline(name, methodName, file.Layer.ToString(), IsToolFile(file),
                                          from.Count == 0 ? "" : string.Join(", ", from.Select(n => $"`{n}`")), summary);
            }

         return found.Values.ToList();
      }

      private static void AppendConversationPath(StringBuilder sb, IReadOnlyList<SourceFile> files, List<Pipeline> pipelines)
      {
         HashSet<string> entries = pipelines.Where(p => p.Name.StartsWith(ConversationService + ".", StringComparison.Ordinal))
                                            .Select(p => p.Method)
                                            .ToHashSet(StringComparer.Ordinal);

         sb.AppendLine("## The character conversation path");
         sb.AppendLine();
         if (entries.Count == 0)
         {
            sb.AppendLine($"`{ConversationService}` no longer calls the model. The conversation path moved; fix `PromptPipelinesMap`.");
            sb.AppendLine();

            return;
         }

         sb.AppendLine($"`{ConversationService}` ({string.Join(", ", entries.OrderBy(e => e, StringComparer.Ordinal).Select(e => $"`{e}`"))}) writes the");
         sb.AppendLine("character's own system prompt (`prompt-sections.md`) and is called from each place below (by name). Every one of");
         sb.AppendLine("them gets the editable files that reach the character prompt.");
         sb.AppendLine();

         List<string> callers = files.Where(f => f.Layer != Layer.Sdk || !f.RelativePath.EndsWith(ConversationService + ".cs", StringComparison.Ordinal))
                                     .SelectMany(f => f.Root.DescendantNodes().OfType<InvocationExpressionSyntax>()
                                                       .Where(c => c.Expression is MemberAccessExpressionSyntax && entries.Contains(CalledName(c) ?? ""))
                                                       .Select(c => $"`{OwnerOf(c)}.{MethodNameOf(c)}` ({CalledName(c)}){(IsToolFile(f) ? ", tool" : "")}"))
                                     .Distinct()
                                     .OrderBy(s => s, StringComparer.Ordinal)
                                     .ToList();
         foreach (string caller in callers) sb.AppendLine($"- {caller}");
         sb.AppendLine();
      }

      private sealed record EditableFile(string Name, string Target);

      private static void AppendFiles(StringBuilder sb, IReadOnlyList<SourceFile> files)
      {
         sb.AppendLine("## Editable files: who reads each one");
         sb.AppendLine();

         ClassDeclarationSyntax? loader = files.SelectMany(f => f.Root.DescendantNodes().OfType<ClassDeclarationSyntax>())
                                               .FirstOrDefault(c => c.Identifier.Text == Loader);
         if (loader == null)
         {
            sb.AppendLine($"`{Loader}` was not found; fix `PromptPipelinesMap`.");
            sb.AppendLine();

            return;
         }

         sb.AppendLine($"Each file `{Loader}` reads (from `ModuleData/Custom/` first, then `ModuleData/`), the member that holds it, and every");
         sb.AppendLine("method outside the loader that reads that member. `{...}` in a name is one file per station, trade or culture.");
         sb.AppendLine();
         sb.AppendLine("| File | Held in | Read by |");
         sb.AppendLine("|---|---|---|");

         var editable = new List<EditableFile>();
         foreach (InvocationExpressionSyntax call in loader.DescendantNodes().OfType<InvocationExpressionSyntax>().Where(c => CalledName(c) == LoaderRead))
         {
            ExpressionSyntax? arg = call.ArgumentList.Arguments.FirstOrDefault()?.Expression;
            string? fileName = arg switch {
               LiteralExpressionSyntax l => l.Token.ValueText,
               InterpolatedStringExpressionSyntax s => string.Concat(s.Contents.Select(c => c is InterpolatedStringTextSyntax t ? t.TextToken.ValueText : "{" + ((InterpolationSyntax) c).Expression + "}")),
               _ => null
            };
            if (fileName == null) continue;

            AssignmentExpressionSyntax? assign = call.Ancestors().OfType<AssignmentExpressionSyntax>().FirstOrDefault();
            string target = assign?.Left switch {
               IdentifierNameSyntax i => i.Identifier.Text,
               ElementAccessExpressionSyntax e => e.Expression.ToString(),
               _ => "(not held)"
            };
            editable.Add(new EditableFile(fileName, target));
         }

         // What the rest of the code can name: a public member that is the target itself, or that reads it. The member that
         // reads the files (Load) and a self-test seam are doors in, not out.
         List<MemberDeclarationSyntax> exposed = loader.Members.Where(m => m.Modifiers.Any(t => t.Text == "public" || t.Text == "internal"))
                                                       .Where(m => !m.DescendantNodes().OfType<InvocationExpressionSyntax>().Any(c => CalledName(c) == LoaderRead))
                                                       .Where(m => NameOf(m)?.EndsWith("ForTest", StringComparison.Ordinal) != true)
                                                       .ToList();

         foreach (EditableFile file in editable.OrderBy(e => e.Name, StringComparer.Ordinal))
         {
            HashSet<string> doors = exposed.Where(m => NameOf(m) == file.Target
                                                       || m.DescendantNodes().OfType<IdentifierNameSyntax>().Any(i => i.Identifier.Text == file.Target))
                                           .Select(NameOf)
                                           .Where(n => n != null)
                                           .Select(n => n!)
                                           .ToHashSet(StringComparer.Ordinal);

            List<string> readers = files.Where(f => !f.RelativePath.EndsWith(Loader + ".cs", StringComparison.Ordinal))
                                        .SelectMany(f => f.Root.DescendantNodes().OfType<MemberAccessExpressionSyntax>()
                                                          .Where(a => a.Expression.ToString().Split('.').Last() == Loader && doors.Contains(a.Name.Identifier.Text))
                                                          .Select(a => $"`{OwnerOf(a)}.{MethodNameOf(a)}`{(IsToolFile(f) ? " (tool)" : "")}"))
                                        .Distinct()
                                        .OrderBy(s => s, StringComparer.Ordinal)
                                        .ToList();

            sb.AppendLine($"| `{file.Name}` | {string.Join(", ", doors.OrderBy(d => d, StringComparer.Ordinal).Select(d => $"`{d}`"))} | {(readers.Count == 0 ? "(no reader found)" : string.Join(", ", readers))} |");
         }

         sb.AppendLine();
      }

      private static string? NameOf(MemberDeclarationSyntax m)
         => m switch {
            PropertyDeclarationSyntax p => p.Identifier.Text,
            MethodDeclarationSyntax me => me.Identifier.Text,
            FieldDeclarationSyntax f => f.Declaration.Variables.FirstOrDefault()?.Identifier.Text,
            _ => null
         };

      private static void AppendProfiles(StringBuilder sb, IReadOnlyList<SourceFile> files)
      {
         List<string> reached = files.Where(f => !f.RelativePath.EndsWith(ProfileLayout + ".cs", StringComparison.Ordinal))
                                     .Where(f => f.Root.DescendantNodes().OfType<IdentifierNameSyntax>().Any(i => i.Identifier.Text == ProfileLayout))
                                     .SelectMany(f => f.Root.DescendantNodes().OfType<ClassDeclarationSyntax>()
                                                       .Where(c => c.DescendantNodes().OfType<IdentifierNameSyntax>().Any(i => i.Identifier.Text == ProfileLayout))
                                                       .Select(c => c.Identifier.Text))
                                     .Where(n => n.EndsWith("PromptBuilder", StringComparison.Ordinal))
                                     .Distinct()
                                     .OrderBy(n => n, StringComparer.Ordinal)
                                     .ToList();

         sb.AppendLine("## Prompt profiles");
         sb.AppendLine();
         sb.AppendLine($"A prompt profile (MCM *Prompt Profile*, `ModuleData/Custom/Prompts/`) reorders, rewords or turns off the sections of");
         sb.AppendLine($"`prompt-sections.md`. Of the prompt builders, only those that use `{ProfileLayout}` are reached: {(reached.Count == 0 ? "none" : string.Join(", ", reached.Select(r => $"`{r}`")))}.");
         sb.AppendLine("Every other pipeline above writes its prompt the same whatever profile is chosen.");
         sb.AppendLine();
      }

      #endregion
   }
}

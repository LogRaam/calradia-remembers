// Code written by Gabriel Mailhot, 19/10/2026.
// docs/maps/placement.md: is each namespace one module, and does each type live where it is used? Gabriel asked (19/10/2026)
// what Graphify computes that our maps lack. dependencies.md already says which namespaces know each other, and which files
// make each pair. This map goes one level down, to the types:
//
//   - COHESION: how many separate parts a namespace falls into when only its own types' links to each other are kept.
//     "Is Diagnostics one module or five?" A namespace in several parts is several modules sharing a folder.
//   - TYPES THAT LIVE AWAY FROM THEIR USERS: a type whose users are mostly in ONE other namespace (Graphify reattaches a
//     node to the community most of its neighbours are in; this is the same vote, on our namespaces). Moving it there is
//     the cheapest cut a cycle can get.
//
// Read from syntax, like every map here: a type is recognised by its NAME, so a name declared in two namespaces is left
// out rather than guessed. Users are counted in FILES, and only inside the type's own layer: the mod using a Logic
// policy is the design, not a misplacement. Counts are in bands so the map moves when a type changes class, not on every
// commit. Informing only, no ratchet: what it shows decides whether one is worth having.

#region

using System.Text;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#endregion

namespace CalradiaRemembers.Tests.Maps
{
   internal static class PlacementMap
   {
      public const string Path = "docs/maps/placement.md";

      /// <summary>A namespace smaller than this is not split into parts: three types are one idea or a coincidence.</summary>
      private const int SmallestNamespaceMeasured = 4;

      /// <summary>A type is listed as living away only when at least this many files of ONE other namespace use it.</summary>
      private const int FewestUsersToMove = 3;

      public static string Generate(IReadOnlyList<SourceFile> files)
      {
         List<TypeAt> types = TypesOf(files);
         Dictionary<string, TypeAt> byName = types.GroupBy(t => t.Name)
                                                  .Where(g => g.Count() == 1)
                                                  .ToDictionary(g => g.Key, g => g.Single(), StringComparer.Ordinal);
         Dictionary<TypeAt, HashSet<SourceFile>> users = UsersOf(files, byName);

         var sb = new StringBuilder();
         sb.AppendLine("# Placement: is each namespace one module, and does each type live where it is used?");
         sb.AppendLine();
         sb.AppendLine("GENERATED by the Maps fixtures in `CalradiaRemembers.Tests/Maps`. Do not edit. A test fails when this file");
         sb.AppendLine("no longer matches the code; see `docs/maps/README.md`.");
         sb.AppendLine();
         sb.AppendLine("Read from syntax: a type is recognised by its name, and a name declared in two namespaces is left out");
         sb.AppendLine($"({types.Count - byName.Count} of {types.Count} types). Users are counted in files, inside the type's own layer only.");
         sb.AppendLine();

         AppendLivingAway(sb, types, byName, users);
         AppendCohesion(sb, types, byName, users);

         return sb.ToString();
      }

      #region private

      private sealed record TypeAt(Layer Layer, string Namespace, string Name);

      /// <summary>Top-level types and delegates, a partial type once.</summary>
      private static List<TypeAt> TypesOf(IReadOnlyList<SourceFile> files)
         => files.SelectMany(f => DeclaredIn(f).Select(name => new TypeAt(f.Layer, f.Namespace, name)))
                 .Distinct()
                 .ToList();

      private static IEnumerable<string> DeclaredIn(SourceFile file)
         => file.Root.DescendantNodes()
                .OfType<MemberDeclarationSyntax>()
                .Where(m => m.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax)
                .Select(m => m switch {
                   BaseTypeDeclarationSyntax type => type.Identifier.Text,
                   DelegateDeclarationSyntax del => del.Identifier.Text,
                   _ => null
                })
                .Where(n => n != null)
                .Select(n => n!);

      /// <summary>For every uniquely named type, the files of its own layer that name it, its own files excluded.</summary>
      private static Dictionary<TypeAt, HashSet<SourceFile>> UsersOf(IReadOnlyList<SourceFile> files, Dictionary<string, TypeAt> byName)
      {
         var users = new Dictionary<TypeAt, HashSet<SourceFile>>();

         foreach (SourceFile file in files)
         {
            var declaredHere = new HashSet<string>(DeclaredIn(file), StringComparer.Ordinal);
            var named = new HashSet<string>(file.Root.DescendantNodes().OfType<SimpleNameSyntax>().Select(n => n.Identifier.Text),
                                            StringComparer.Ordinal);

            foreach (string name in named)
            {
               if (declaredHere.Contains(name) || !byName.TryGetValue(name, out TypeAt? type) || type.Layer != file.Layer) continue;
               if (!users.TryGetValue(type, out HashSet<SourceFile>? set)) users[type] = set = new HashSet<SourceFile>();
               set.Add(file);
            }
         }

         return users;
      }

      private static void AppendLivingAway(
         StringBuilder sb, List<TypeAt> types, Dictionary<string, TypeAt> byName, Dictionary<TypeAt, HashSet<SourceFile>> users)
      {
         var rows = new List<(TypeAt Type, string Elsewhere, int There, int Home, int All)>();

         foreach (TypeAt type in types.Where(t => byName.ContainsKey(t.Name)))
         {
            if (!users.TryGetValue(type, out HashSet<SourceFile>? using_) || using_.Count == 0) continue;

            int home = using_.Count(f => f.Namespace == type.Namespace);
            IGrouping<string, SourceFile>? top = using_.Where(f => f.Namespace != type.Namespace)
                                                       .GroupBy(f => f.Namespace)
                                                       .OrderByDescending(g => g.Count())
                                                       .ThenBy(g => g.Key, StringComparer.Ordinal)
                                                       .FirstOrDefault();
            if (top == null) continue;

            int there = top.Count();
            if (there < FewestUsersToMove || there * 2 <= using_.Count) continue;

            rows.Add((type, top.Key, there, home, using_.Count));
         }

         sb.AppendLine("## Types that live away from their users");
         sb.AppendLine();
         sb.AppendLine($"Most of the files that use the type (more than half, and at least {FewestUsersToMove}) are in ONE other namespace. Either it");
         sb.AppendLine("belongs there, or it is a shared foundation that should say so. Moving one is the cheapest cut a cycle can get;");
         sb.AppendLine("`dependencies.md` shows which pairs it would untangle. Bands: a few (1-5), several (6-15), many (16+).");
         sb.AppendLine();

         if (rows.Count == 0)
         {
            sb.AppendLine("None.");
            sb.AppendLine();

            return;
         }

         sb.AppendLine("| Type | Lives in | Used mostly by | Users there | Users at home |");
         sb.AppendLine("|---|---|---|---|---|");

         foreach (var row in rows.OrderBy(r => r.Type.Layer)
                                 .ThenBy(r => r.Type.Namespace, StringComparer.Ordinal)
                                 .ThenBy(r => r.Type.Name, StringComparer.Ordinal))
            sb.AppendLine($"| `{row.Type.Name}` | `{row.Type.Namespace}` | `{row.Elsewhere}` | {Band(row.There)} | {(row.Home == 0 ? "none" : Band(row.Home))} |");

         sb.AppendLine();
      }

      private static void AppendCohesion(
         StringBuilder sb, List<TypeAt> types, Dictionary<string, TypeAt> byName, Dictionary<TypeAt, HashSet<SourceFile>> users)
      {
         sb.AppendLine("## Cohesion: how many parts each namespace falls into");
         sb.AppendLine();
         sb.AppendLine("Only the links between a namespace's OWN types are kept (one type's file names the other). A namespace in one");
         sb.AppendLine("part is one module. Several parts are several modules sharing a folder; types on their own are linked to no");
         sb.AppendLine("sibling at all (often fine for a data type or a Harmony patch, worth a look for a service). Density is the share");
         sb.AppendLine($"of possible sibling links that exist: tight (30% or more), medium (10% or more), loose. Namespaces of {SmallestNamespaceMeasured} types or more.");
         sb.AppendLine("In Logic, a type on its own is the design (each pure rule stands alone and the mod calls it); there, the PARTS");
         sb.AppendLine("count is what to read: a namespace of many unrelated parts is a folder of things that could each have their own.");
         sb.AppendLine();
         sb.AppendLine("| Namespace | Types | Parts | Types on their own | Density |");
         sb.AppendLine("|---|---|---|---|---|");

         var rows = new List<(TypeAt First, int Count, int Parts, int Alone, string Density)>();

         foreach (IGrouping<(Layer, string), TypeAt> ns in types.Where(t => byName.ContainsKey(t.Name)).GroupBy(t => (t.Layer, t.Namespace)))
         {
            List<TypeAt> members = ns.ToList();
            if (members.Count < SmallestNamespaceMeasured) continue;

            // Undirected sibling links: a file of A names B (B's users include a file declaring A).
            var index = members.Select((t, i) => (t, i)).ToDictionary(p => p.t.Name, p => p.i, StringComparer.Ordinal);
            var links = new HashSet<(int, int)>();
            foreach (TypeAt b in members)
            {
               if (!users.TryGetValue(b, out HashSet<SourceFile>? using_)) continue;

               foreach (SourceFile file in using_.Where(f => f.Namespace == ns.Key.Item2))
                  foreach (string a in DeclaredIn(file))
                     if (index.TryGetValue(a, out int ai) && a != b.Name)
                        links.Add((Math.Min(ai, index[b.Name]), Math.Max(ai, index[b.Name])));
            }

            int[] parent = Enumerable.Range(0, members.Count).ToArray();
            int Find(int x) => parent[x] == x ? x : parent[x] = Find(parent[x]);
            foreach ((int x, int y) in links) parent[Find(x)] = Find(y);

            var linked = new HashSet<int>(links.SelectMany(l => new[] {l.Item1, l.Item2}));
            int alone = members.Count - linked.Count;
            int parts = linked.Select(Find).Distinct().Count();
            double density = links.Count / (members.Count * (members.Count - 1) / 2.0);

            rows.Add((members[0], members.Count, parts, alone, density >= 0.3 ? "tight" : density >= 0.1 ? "medium" : "loose"));
         }

         foreach (var row in rows.OrderByDescending(r => r.Parts)
                                 .ThenByDescending(r => r.Alone)
                                 .ThenBy(r => r.First.Namespace, StringComparer.Ordinal))
            sb.AppendLine($"| `{row.First.Namespace}` | {row.Count} | {row.Parts} | {row.Alone} | {row.Density} |");

         sb.AppendLine();
      }

      private static string Band(int count) => count >= 16 ? "many" : count >= 6 ? "several" : "a few";

      #endregion
   }
}
